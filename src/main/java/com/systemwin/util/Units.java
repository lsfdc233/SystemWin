package com.systemwin.util;

/**
 * Helpers to normalize unit names between the CLI form and Windows service names.
 *
 * 这个类到底是干什么用的呢？我们慢慢来说，别着急。
 * 在 systemd 的世界里，一个"服务单元"（unit）的标准叫法通常要带上 ".service" 这个后缀，
 * 比如说 "nginx.service"；但是命令行（CLI）里用户图省事，往往只敲 "nginx" 三个字母，
 * 连后缀都懒得打。反过来，Windows 的"服务名"（service name）又是另外一种规矩：
 * 它纯粹就是那个不带后缀的名字，比如 "nginx"。
 *
 * 所以你看，同一个东西，在不同的场景下有完全不同的两种写法，
 * 这就非常容易让人晕头转向、出各种莫名其妙的 bug。
 * 我们这个 Units 工具类存在的意义，就是专门充当这两种写法之间的"翻译官"，
 * 负责把一种格式转换成另一种格式，让调用方永远不用自己去关心
 * "到底要不要加 .service 后缀"这种鸡毛蒜皮的细节。
 *
 * 简单总结一下这个类的作用：
 * 1. normalize()   —— 把用户随手输入的短名字，补全成标准的 "xxx.service" 形式；
 * 2. serviceName() —— 反过来，把带后缀的完整名字，去掉后缀还原成纯名字。
 *
 * 这两个方法正好是一对"互逆"的操作，一个加后缀、一个去后缀，
 * 你中有我、我中有你，配合起来用就可以在两种体系之间自由切换了。
 */
public final class Units {

    /**
     * 私有构造方法。
     *
     * 为什么要把它写成 private 呢？这可不是随便乱写的，是有讲究的。
     * 因为这个类里面全是静态方法，也就是说它本质上只是一个"工具容器"，
     * 里面装的都是可以直接用类名调用的静态工具函数，
     * 根本不需要、也不应该被 new 出任何实例来用。
     *
     * 如果把构造方法设成 private，就等于堵死了外面 new Units() 的这条路，
     * 这样别人就只能老老实实通过 Units.normalize(...) 这种静态方式去调用，
     * 想犯"无意义地创建对象"这种错误都没机会，
     * 从设计上就保证了工具类的正确用法，非常贴心。
     */
    private Units() {
        // 方法体是空的，什么都不用做，
        // 因为我们只需要"禁止实例化"这个效果本身，
        // 并不需要构造方法里执行任何初始化逻辑。
    }

    /**
     * "nginx" -> "nginx.service"; "nginx.service" stays unchanged.
     *
     * 翻译一下：把 "nginx" 这种短名字规范化成 "nginx.service"；
     * 如果传入的本来就已经是 "nginx.service" 这种带后缀的完整形式，
     * 那就原封不动地直接返回，不做任何多余的处理。
     *
     * 这个方法的具体执行流程是这样的：
     * 1. 先判断传入的 unit 是不是 null（空引用）。
     *    为什么要判断 null 呢？因为 null 是个非常危险的"坑"，
     *    如果不加判断就直接调用 unit.trim()，程序立刻就会抛
     *    NullPointerException（空指针异常），整个调用链就直接炸了。
     *    所以我们先把它挡在门外，遇到 null 就返回一个空字符串 ""，
     *    宁可给一个空结果，也绝不能让程序崩溃，这就是防御式编程的思想。
     * 2. 用 trim() 把字符串首尾的空格、制表符、换行符等空白字符都去掉。
     *    这一步也很重要，因为用户从命令行输入内容的时候，
     *    经常手一抖就多敲了几个空格，比如 " nginx "，
     *    如果不 trim，后面用 endsWith(".service") 判断就会出错。
     * 3. 判断去掉空格之后的字符串是不是以 ".service" 结尾。
     *    如果是，说明用户已经给了完整形式，直接原样返回即可；
     *    如果不是，说明用户给的是短名字，那就老老实实把
     *    ".service" 拼到后面，凑成完整形式再返回。
     *
     * 这样设计的好处是：调用方无论拿到的是哪种形式的输入，
     * 经过 normalize 处理之后，得到的永远是统一的 "xxx.service" 格式，
     * 后续所有代码都可以放心地假设这个名字一定带后缀，省心省力。
     */
    public static String normalize(String unit) {
        // 第一步：防御空值。
        // 记住，任何从外部传进来的参数都可能是 null，
        // 尤其是用户输入的东西，绝对不能想当然地认为它非空。
        if (unit == null) {
            // 返回空字符串而不是 null，也是个讲究：
            // 让调用方后续可以放心地使用这个返回值，
            // 比如可以直接调用 result.endsWith(...) 而不用担心空指针。
            return "";
        }
        // 第二步：去掉首尾空白。
        // trim() 只处理首尾的空白，不会动字符串中间的内容，
        // 所以像 "nginx web" 这种中间带空格的字符串不会被误伤。
        String u = unit.trim();
        // 第三步：判断是否已经带上了 ".service" 后缀。
        // endsWith 是从字符串的末尾开始匹配的，
        // 也就是说只有后缀正好在最后面才会返回 true。
        if (u.endsWith(".service")) {
            // 已经带后缀了？那就什么都不用改，直接原样返回。
            // 注意这里返回的是 trim 过之后的 u，而不是原始传入的 unit，
            // 这样顺手就把首尾多余的空格也一并清理干净了。
            return u;
        }
        // 走到这里，说明 u 是 "nginx" 这种不带后缀的短名字，
        // 那就用字符串拼接（+ 运算符）把 ".service" 追加到末尾，
        // 拼出 "nginx.service" 这种完整标准形式再返回。
        return u + ".service";
    }

    /**
     * "nginx.service" -> "nginx"; "nginx" stays unchanged (Windows service name).
     *
     * 翻译一下：把 "nginx.service" 这种带后缀的完整形式，去掉后缀变成 "nginx"；
     * 如果传入的本来就是 "nginx" 这种不带后缀的纯名字，那就原样返回。
     * 注意括号里的说明：这个方法的返回值是给 Windows 服务名用的，
     * 因为 Windows 的服务名约定是不带 ".service" 后缀的。
     *
     * 这个方法跟上面的 normalize() 正好是相反的操作，
     * 一个是"补全后缀"，一个是"摘除后缀"，
     * 两者配合起来，就可以在 systemd 风格和 Windows 风格之间来回切换了。
     *
     * 具体的执行流程：
     * 1. 同样先做 null 防御，防止空指针异常，null 就返回空字符串；
     * 2. 同样先 trim() 去掉首尾空白，保证判断的准确性；
     * 3. 判断是否以 ".service" 结尾：
     *    - 如果是，就调用 substring 把末尾的 ".service" 这 8 个字符裁掉，
     *      剩下前面的部分作为服务名返回；
     *    - 如果不是，说明本来就没有后缀，直接原样返回即可。
     *
     * 这里有个小细节值得注意：
     * ".service".length() 的长度是 8，但是我们不直接写死数字 8，
     * 而是通过调用 length() 动态算出来。
     * 这样写的好处是：万一以后后缀的写法变了（比如改成 ".svc"），
     * 这里只需要改一处常量，别的地方都不用动，可维护性更好。
     * 而且直接写 8 这种"魔法数字"（magic number），
     * 读代码的人还得心里默默数一下才知道 8 是哪来的，很不友好。
     */
    public static String serviceName(String unit) {
        // 和 normalize() 一样，第一步还是防 null，这是所有工具方法的"基本功"。
        if (unit == null) {
            // 返回空字符串，保证调用方后续操作的安全。
            return "";
        }
        // 去掉首尾空白，防止用户手滑多打了空格导致判断失败。
        String u = unit.trim();
        // 判断传入的名字是不是带 ".service" 后缀的完整形式。
        if (u.endsWith(".service")) {
            // 带后缀的情况：把后缀裁掉，只留前面的名字部分。
            // substring(0, 长度差) 的含义是：
            // 从第 0 个字符开始，一直截取到"去掉后缀之后"的那个位置为止，
            // 也就是把末尾的 ".service" 整体剪掉，返回剩余部分。
            // 举例：u = "nginx.service"，".service".length() = 8，
            //       那么 0 到 (12 - 8) = 4，截取出来就是 "nginx"，完美。
            return u.substring(0, u.length() - ".service".length());
        }
        // 本来就不带后缀，说明用户给的就是纯服务名，
        // 那就直接原样返回，什么都不用改。
        return u;
    }
}
