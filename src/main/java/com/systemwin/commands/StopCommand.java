package com.systemwin.commands;

import com.systemwin.cli.Args;
import com.systemwin.service.WindowsServiceManager;
import com.systemwin.util.Units;

/*
 * 【这个文件到底是干什么的？先给你讲个背景故事，别嫌我啰嗦】
 * SystemWin 是一个模仿 systemd（Linux 上的服务管理工具）的命令行程序，
 * 只不过它管理的不是 Linux 服务，而是 Windows 系统上的服务。
 * 用户会敲类似 "systemwin stop nginx" 这样的命令，意思是：
 * "把 nginx 这个服务给我停掉！"
 *
 * 而 StopCommand 这个类，就是专门负责响应 "stop" 这个子命令的"接待员"。
 * 用户一敲 stop 命令，程序就会创建本类的一个对象，然后调用它的 run()
 * 方法，把用户剩下的参数（也就是要停哪些服务）交给它处理。
 *
 * 注意它的名字：Stop（停止）+ Command（命令），连起来就是"停止命令"。
 * 在 commands 这个包里，你会发现还有 StartCommand（启动命令）、
 * RestartCommand（重启命令）等等，它们长得都非常像，几乎是一个模子
 * 刻出来的——这是因为它们都实现了同一个 Command 接口，遵守同一套
 * 游戏规则：对外只暴露一个 run(Args) 方法，程序主循环只要调用它
 * 就行，根本不需要关心每个命令内部的细节。这就是"多态"的好处：
 * 面对不同的子命令，主程序用完全一样的调用姿势，具体怎么干，
 * 交给各自的实现类去操心。
 */

/** Stops one or more services: {@code systemwin stop <unit>...}. */
/*
 * （上面这句英文注释的中文翻译：停止一个或多个服务。
 *  用法是：systemwin stop <unit>...，其中 <unit> 是服务单元的名字，
 *  而且可以写多个，中间用空格隔开。比如 "systemwin stop nginx mysql"
 *  就是一条命令同时停掉 nginx 和 mysql 两个服务。
 *  这里的 {@code ...} 只是 javadoc 的一种排版语法，表示里面是代码片段，
 *  生成文档的时候会用等宽字体显示，方便阅读，没有别的玄机。）
 */
public final class StopCommand implements Command {

    /*
     * 【字段 ctx 是干什么的？—— 命令的"百宝箱"】
     * ctx 是 CommandContext（命令上下文）的缩写。还记得我们说过吗，
     * 每个命令在执行的时候都需要一些"公共依赖"，比如：
     *   - i18n：国际化对象，负责把各种提示信息翻译成用户选择的语言；
     *   - services：Windows 服务管理器，负责真正去操作系统层面的服务。
     * CommandContext 就是装这些东西的"公文包"，命令拿到它，
     * 想用哪个依赖就直接 ctx.xxx 取出来用，非常方便。
     *
     * 为什么不让命令自己 new 一份这样的依赖呢？因为这两个依赖的创建
     * 逻辑比较麻烦（比如服务管理器内部要封装一堆 PowerShell 调用），
     * 如果每个命令都自己造一份，代码就会到处重复粘贴，而且以后想
     * 统一修改依赖的创建方式时还得逐个命令去改，维护成本极高。
     * 所以设计上采用"依赖注入"的思路：依赖由外部统一创建好，
     * 通过构造函数塞给命令，命令只负责"拿来就用"。
     *
     * 另外注意 private final 这两个修饰符的含义：
     *   - private：只有本类内部能访问这个字段，外面碰都碰不到，
     *     封装性好，不会被人乱改；
     *   - final：这个引用一旦赋值就固定了，不能再指向别的对象，
     *     防止有人偷偷把上下文换掉，导致整个命令的行为变得不可预测。
     */
    private final CommandContext ctx;

    /*
     * 【构造函数：命令对象是怎么出生的？】
     * 构造函数的名字和类名一模一样（都是 StopCommand），当外部执行
     * "new StopCommand(ctx)" 的时候，这个函数就会自动被调用。
     * 它的任务只有一个：把外面传进来的 CommandContext 保存到自己的
     * ctx 字段里，留待以后 run() 方法使用。
     *
     * 你可能会问：为什么命令不自己 new 一个 CommandContext 呢？
     * 因为同一个上下文对象可以在多个命令之间共享（比如先 new 出
     * 一个上下文，再把它同时传给 StartCommand 和 StopCommand），
     * 而且命令本身不应该关心依赖是怎么造出来的——"只管用，不管造"。
     * 这种通过构造函数把依赖递进来的写法叫"构造函数注入"
     * （Constructor Injection），它还有个额外的好处：写单元测试的
     * 时候可以传一个假的（mock）上下文进来，而不必真的去操作
     * Windows 系统服务，测试又安全又快速。
     */
    public StopCommand(CommandContext ctx) {
        // 这里就是简单的"接住"动作：把参数 ctx 赋给成员字段 this.ctx。
        // 注意为什么要写 this.ctx 而不是直接写 ctx？
        // 因为参数的名字和字段的名字都叫 ctx，Java 编译器会优先认
        // 离得最近的参数，写 this.ctx 才能明确告诉编译器：
        // "我要的是这个对象的字段，不是方法参数"，这样才不会搞混。
        this.ctx = ctx;
    }

    /*
     * 【run() 方法：整个命令的"总指挥部"】
     * Command 接口规定每个命令都必须实现 run(Args) 方法，它接收一个
     * Args 对象（里面装着用户敲下的所有参数），然后返回一个整数作为
     * "退出码"（exit code）：返回 0 表示成功，非 0 表示出错了。
     * 这个退出码最终会一路传回给操作系统，脚本程序可以用它来判断
     * 命令到底是成功了还是失败了，这是命令行工具的老规矩。
     *
     * 本方法的执行逻辑分成两大块：
     *   1. 先检查用户有没有给出要停的服务名。如果一个都没给，
     *      那就打印一条错误提示，直接返回 1（失败），什么都不做；
     *   2. 如果给了，就逐个处理：对每一个服务名调用 stopOne()
     *      去真正执行停止操作，并把所有子操作的结果汇总起来返回。
     * 注意这里支持一次停多个服务（比如 "systemwin stop a b c"），
     * 这种"一次处理多个"的设计跟 systemctl 的习惯是一致的，
     * 用户不用一条一条地敲命令，省事很多。
     */
    @Override
    public int run(Args args) {
        // —— 第一大步：参数检查，先看看用户到底有没有说要停谁 ——
        // positional 是 Args 对象里的"位置参数"列表，也就是用户敲的
        // 那些不带横杠、不带选项名的普通参数。比如 "systemwin stop
        // nginx" 这条命令里，positional 里就装着一个元素 "nginx"。
        // 如果这个列表是空的，说明用户只敲了 "systemwin stop"，
        // 后面什么都没跟——那我们根本不知道要停哪个服务，只能报错。
        if (args.positional.isEmpty()) {
            // i18n.msg("err.unit.required", "stop") 的意思是：
            // 去国际化消息表里查键为 "err.unit.required" 的文本，
            // 把文本里的占位符替换成 "stop"，然后打印到控制台。
            // 用户设置的是中文环境，这里就会显示中文的
            // "必须指定要停止的服务单元"之类的提示；
            // 用户设置的是英文环境，则显示对应的英文提示。
            // 这就是 i18n 对象存在的意义：程序代码里不写死任何一句
            // 用户能看到的文字，全部交给翻译表去管。
            System.out.println(ctx.i18n.msg("err.unit.required", "stop"));
            // 返回 1 表示"用法错误"。程序主循环拿到非零退出码，
            // 就会把整个命令判定为失败，并把 1 原样返回给操作系统。
            return 1;
        }
        // —— 第二大步：逐个停止用户指定的每一个服务 ——
        // code 变量用来"汇总"最终结果：我们允许一次停好几个服务，
        // 但每个服务可能有的成功、有的失败，最后总要给用户一个
        // 总体的结论。这里先把初始值设成 0，意思就是"暂时全部成功"。
        int code = 0;
        // for 循环遍历用户给的所有服务名，一个一个地处理。
        // 这里用的是增强 for 循环（for-each），它会自动从列表里
        // 取出每一个元素，依次赋值给 unit 变量，然后执行循环体；
        // 列表里有多少个服务名，循环体就执行多少次，非常直观。
        for (String unit : args.positional) {
            // 调用私有方法 stopOne() 去停止当前这个服务，
            // 它会返回这个服务的处理结果码：0 成功，非 0 失败。
            int c = stopOne(unit);
            // 只要有任何一次操作失败了（c != 0），我们就把总结果
            // code 改成那个失败码。注意这里不是直接 code = c，
            // 而是"如果 c 非零才赋值"——为什么要这么绕呢？
            // 因为如果后面还有成功的操作（返回 0），我们不能让 0
            // 把之前已经记录下来的失败码给覆盖掉。
            // 也就是说：只要有任何一个服务失败，最终结果就是失败；
            // 只有所有服务全部成功，最终结果才是 0。
            // 这种"取最坏结果"的汇总方式在批处理场景里非常常见，
            // 你可以把它理解为"一票否决制"。
            if (c != 0) {
                code = c;
            }
        }
        // 把所有服务都处理完之后，把汇总好的退出码返回给调用方。
        // 调用方（也就是命令分发器）拿到这个数字后，会决定整个
        // systemwin stop 命令最终是成功（0）还是失败（非 0）。
        return code;
    }

    /*
     * 【stopOne() 方法：真正动手停服务的"一线工人"】
     * run() 只负责"调度"和"汇总"，而真正的脏活累活都在这一个
     * 私有方法里干。它接收一个"原始的服务名"（rawUnit，也就是
     * 用户原封不动敲进来的名字，可能带着多余的空格，可能没带
     * .service 后缀），然后按顺序做下面这几件事：
     *   1. 规范化名字（补全 .service 后缀、去掉首尾空格）；
     *   2. 检查这个服务到底存不存在，不存在就提前报错退出；
     *   3. 存在的话，调用服务管理器去真正停止它；
     *   4. 根据停止的结果打印不同的提示信息；
     *   5. 返回一个退出码，交给 run() 去汇总。
     *
     * 为什么这个方法要设计成 private（私有）呢？因为它只是本类
     * 内部的一个"帮手"，外界根本不需要直接调用它——外面只要调用
     * 公开的 run() 就够了。把不必要暴露的方法藏起来，类的对外
     * 接口就更简洁，别人也不容易误用，这正是封装（encapsulation）
     * 思想的具体体现。
     */
    private int stopOne(String rawUnit) {
        // 第一步：规范化服务名。
        // Units.normalize() 会把 "nginx" 变成 "nginx.service"；
        // 如果传入的本来就已经带上了 ".service" 后缀，那就原样返回，
        // 顺带还会把首尾多余的空格清理干净。
        // 为什么要做这一步？因为用户输入的风格五花八门，我们必须在
        // 统一的"标准格式"下做后续的判断和比较，否则同一个服务
        // 一会儿写 "nginx"、一会儿写 " nginx.service "，程序就会
        // 认不出它们是同一个东西，从而出各种莫名其妙的 bug。
        String unit = Units.normalize(rawUnit);
        // 第二步：把标准化的名字转换成 Windows 服务名。
        // 注意，Windows 系统里的服务名是不带 ".service" 后缀的
        // （比如就叫 "nginx"），而 Units.serviceName() 正好负责
        // 把后缀摘掉，还原成服务管理器认识的那个纯名字。
        // 你看，这里就是 normalize() 和 serviceName() 这对"互逆方法"
        // 配合使用的经典场景：先补后缀、再去后缀，绕了一圈，最终
        // 拿到的是 Windows 服务控制管理器真正认得的那个名字。
        String name = Units.serviceName(unit);
        // 第三步：检查服务是否存在。
        // exists() 是服务管理器提供的一个查询方法，它会去 Windows 的
        // 服务列表里翻一翻，看看有没有叫这个名字的服务。
        // 为什么停止之前要先检查存在性？因为去停一个根本不存在的
        // 服务，Windows 底层会返回一堆天书一样的错误码；与其让用户
        // 面对看不懂的报错，不如我们自己先查一遍，给出友好清晰的
        // 提示。这就是"把错误挡在门口"的防御式编程思想。
        if (!ctx.services.exists(name)) {
            // 服务不存在！打印"找不到该服务"的提示（具体文字根据
            // 用户设置的语言自动翻译）。注意这里传给 msg() 的是
            // unit（规范化之后的名字），这样提示信息里显示的服务名
            // 是规规矩矩的完整形式，用户看着更清楚。
            System.out.println(ctx.i18n.msg("err.unit.not.found", unit));
            // 返回 4 作为"服务不存在"的专属退出码。
            // 这个数字是程序内部约定好的"暗号"，脚本可以根据不同
            // 的非零退出码区分出不同的错误类型，方便自动化处理。
            return 4;
        }
        // 第四步：一切检查都通过了，打印"正在停止 xxx..."的提示。
        // 先把话说出去，让用户知道程序正在干活、没有卡死，
        // 这也是命令行工具"有反馈"的基本素养。
        System.out.println(ctx.i18n.msg("stop.stopping", unit));
        // 第五步：调用服务管理器的 stop() 方法，真正去停止服务。
        // 这一步内部会去调用 Windows 的 sc.exe 之类的系统工具，
        // 然后返回一个 ActionResult（操作结果）对象给我们。
        // 注意这里返回的是一个"结果对象"，而不是简单的 true/false，
        // 因为结果里还带着错误码（code）等详细信息，
        // 光一个布尔值根本不够用——后面我们马上就会用到这个错误码。
        WindowsServiceManager.ActionResult res = ctx.services.stop(name);
        // 第六步：根据结果分情况处理。
        // res.ok() 表示这次停止操作"是否被我们认定为成功"。
        // 注意措辞是"认定为"，为什么？因为下面马上就有个例外情况，
        // 有些在别人眼里算"失败"的结果，在我们这里算"成功"。
        if (res.ok()) {
            // 走到这里，说明服务管理器认为这次操作成功了。
            // 但是！成功也还分两种情况，需要进一步区分一下：
            if (res.code() == 1062) {
                // 错误码 1062 的含义是 ERROR_SERVICE_NOT_ACTIVE，
                // 翻译成人话就是"这个服务本来就没在运行"。
                // 去停一个本来就没运行的服务，Windows 会返回 1062，
                // 但我们的设计把它也当作"成功"来处理——因为用户
                // 想要达到的结果（服务处于停止状态）已经达到了嘛，
                // 没必要大惊小怪地报错。
                // 这跟 systemctl stop 的行为是一致的：操作是幂等的
                // （idempotent），停一个本来就没在跑的服务也不会报错，
                // 停几次结果都一样。所以这里打印的是
                // "服务本来就没有运行"这种温和的提示，而不是
                // 红着脸说"停止失败"。有趣的是，StartCommand 里也有
                // 一模一样的套路：启动时如果遇到 1056（服务已在运行），
                // 同样当作成功处理。一个容忍 1056，一个容忍 1062，
                // 是不是有种镜像对称的美感？
                System.out.println(ctx.i18n.msg("stop.notstarted", unit));
            } else {
                // 错误码不是 1062，说明服务真的是被我们成功停掉的，
                // 那就打印"已停止"的提示，皆大欢喜。
                System.out.println(ctx.i18n.msg("stop.stopped", unit));
            }
            // 操作成功，返回 0，表示这个服务停得漂亮，run() 那边
            // 看到 0 就知道这一轮是成功的，不会把总结果改坏。
            return 0;
        }
        // 走到这里，说明 res.ok() 是 false，也就是停止失败了。
        // 打印"停止失败"的提示。注意这里还调用了 errorMessage()，
        // 它会把原始的错误码（比如 1062 之类的数字）翻译成人类
        // 能看懂的说明文字，一并传给 msg() 拼接进提示里打印出来。
        // 这样用户既知道"失败了"，还知道"为什么失败"，
        // 而不是面对一个冷冰冰的数字干瞪眼。
        System.out.println(ctx.i18n.msg("stop.failed", unit,
                ctx.services.errorMessage(res.code())));
        // 失败就返回 1，交给 run() 去汇总成最终的失败结果。
        // 注意这里返回的 1 和上面"服务不存在"返回的 4 是不同的，
        // 这样脚本就能区分"服务不存在"和"停止过程出错"两类问题。
        return 1;
    }
}
