package com.systemwin.commands;

/*
 * 【包的用途，先给你介绍一下背景】
 * 这个包名叫 commands，也就是"命令"包。SystemWin 是一个命令行工具，
 * 它把用户敲进来的命令（比如"查询某个 Windows 服务"、"启动服务"、
 * "停止服务"、"查看帮助"等等）都拆成了一个个独立的"子命令"来执行。
 * 所有跟"子命令"相关的类都放在这个包里，方便统一管理。
 *
 * 你可能会问：那"子命令"之间有什么共同点呢？答案就是——它们几乎都
 * 需要用到一些公共的依赖对象。比如所有命令都要输出文字给用户看，
 * 而输出的文字要考虑语言（中文还是英文），这就需要一个"国际化"对象；
 * 又比如很多命令都要去操作 Windows 服务，这就需要一个"服务管理器"对象。
 * 如果每个命令都自己 new 一份这样的对象，代码就会大量重复，而且以后
 * 想换一种实现方式的时候，还要一个一个去改，非常麻烦。
 *
 * 所以我们的设计思路是：把这些公共依赖"打包"进一个统一的"上下文"
 * （Context）对象里，谁需要就把它拿过去用。这个思想在编程里非常常见，
 * 你以后看 Spring、看各种框架，到处都能看到"Context"（上下文）这个词，
 * 它本质上就是"把大家都要用的东西集中放在一起，再传来传去"。
 */

import com.systemwin.I18n;
import com.systemwin.service.WindowsServiceManager;

/**
 * Shared dependencies handed to every command.
 * （中文翻译：本类保存的是"要传递给每一个命令"的共享依赖对象。）
 */
/*
 * 【这个类到底是干什么的？我们来慢慢讲】
 * CommandContext 直译过来就是"命令上下文"。什么叫"上下文"呢？你可以
 * 把它想象成一个"工具箱"或者"公文包"：里面放着各种命令在执行时需要用
 * 到的东西。我们的命令在执行之前，会先把这个上下文准备好，然后把它
 * 交给命令去用。这样一来：
 *
 *  1. 命令本身不需要关心这些依赖是怎么创建出来的，它们拿来就用；
 *  2. 创建依赖的逻辑只写一遍，不会在十几个命令里重复粘贴；
 *  3. 以后如果依赖的创建方式变了（比如换了实现类），我们只需要改
 *     这一个地方，其他命令完全不用动，维护起来特别轻松。
 *
 * 这个类被声明成 final，意思是"不允许被继承"。为什么不让继承呢？因为
 * 它只是一个装依赖的"简单容器"，本身没有扩展的需求，把它封死可以避免
 * 别人乱继承、乱改写，让代码更安全、更不容易出 bug。
 */
public final class CommandContext {

    /*
     * 【字段一：i18n（国际化/多语言支持对象）】
     * i18n 这个名字看着有点奇怪对吧？它其实是 Internationalization
     * （国际化）这个英文单词的缩写：i + 中间的 18 个字母 + n，所以叫
     * i18n。这是编程界的一个老传统写法。
     *
     * 它有什么用呢？SystemWin 支持中文和英文两种界面语言。用户设置了
     * 某种语言之后，程序里所有提示信息、报错信息都要用对应的语言显示
     * 出来。这个 i18n 对象就是干这件事的：你给它一个"消息的键"，它就
     * 根据当前语言返回对应的翻译文本。比如键是 "service.not.found"，
     * 英文环境下它就返回 "Service not found."，中文环境下它就返回
     * "找不到该服务。"。
     *
     * 注意这里用的是 public final：public 表示别的类可以直接访问，
     * final 表示这个引用一旦赋值就不能再指向别的对象了。这样设计是
     * 故意的——依赖应该是"只读的"，谁也不许偷偷把它换掉，否则整个
     * 程序的翻译行为就会乱套。
     */
    public final I18n i18n;

    /*
     * 【字段二：services（Windows 服务管理器对象）】
     * 这个对象负责和 Windows 操作系统的"服务控制管理器"（Service
     * Control Manager，简称 SCM）打交道。Windows 里有一大堆后台服务，
     * 比如打印机服务、时间同步服务等等，SystemWin 的核心功能就是帮你
     * 查看、启动、停止这些服务。
     *
     * 具体来说，查询服务信息时它内部会用 PowerShell 调用
     * Get-CimInstance Win32_Service；而启动、停止等修改操作则通过
     * sc.exe 和 New-Service 来实现。这些细节命令完全不需要关心，
     * 它们只要调用 services 上的方法就可以了——这就是"封装"的好处：
     * 复杂的内部实现被藏起来，外面只露出简单好用的接口。
     *
     * 它和上面的 i18n 关系也很密切：服务管理器在报错的时候，需要用
     * i18n 把错误信息翻译成用户选择的语言，所以我们创建它的时候，
     * 要把 i18n 传进去给它用。你看，这就是"依赖注入"：谁需要什么，
     * 就把什么递给谁，而不是自己偷偷去 new。
     */
    public final WindowsServiceManager services;

    /*
     * 【构造函数：上下文对象是怎么出生的？】
     * 构造函数的名字和类名一模一样（CommandContext），它在对象被
     * new 出来的那一刻自动执行，负责把对象"初始化好"。
     *
     * 这个构造函数的参数只有一个：i18n。也就是说，创建上下文的时候，
     * 外部必须先把"国际化对象"准备好递进来。为什么只传 i18n 就够了？
     * 因为 services 对象完全可以由 i18n 推导出来——服务管理器反正
     * 需要 i18n 才能工作，干脆就在构造函数里顺手 new 一个出来，这样
     * 调用方就不需要每次手动创建两个对象了，省事又不容易出错。
     *
     * 你可能会想：为什么不让调用方把两个对象都传进来呢？那样也不是
     * 不行，但我们的选择是"让构造函数自己负责组装"。这是一个小小的
     * 设计取舍：调用方只需要关心"语言"，至于服务管理器怎么造出来、
     * 需不需要换实现，都是 CommandContext 内部的事情，外面一概不
     * 用操心。这也让所有命令的使用方式保持统一：先 new 一个
     * CommandContext，然后想怎么用就怎么用。
     */
    public CommandContext(I18n i18n) {
        // 第一步：把外部传进来的 i18n 保存到自己的字段里，供以后使用。
        this.i18n = i18n;

        // 第二步：用这个 i18n 创建出服务管理器，并同样保存下来。
        // 注意这里的 new 意味着每次创建 CommandContext 都会附带创建
        // 一个全新的 WindowsServiceManager，它们之间是"组合"关系。
        this.services = new WindowsServiceManager(i18n);
    }
}
