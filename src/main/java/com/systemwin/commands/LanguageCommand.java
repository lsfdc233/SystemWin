package com.systemwin.commands;

import com.systemwin.I18n;
import com.systemwin.cli.Args;

/**
 * {@code systemwin language} lists the available languages;
 * {@code systemwin language <lang>} switches the language (persisted in
 * %APPDATA%\SystemWin\config.properties and applied from the next run on).
 */
/*
 * ============================================================================
 * 【类级别的中文说明，写给第一次看这段代码的同学】
 * ============================================================================
 * 这个类的名字叫做 LanguageCommand，翻译成中文就是“语言命令”，它的任务非常单一：
 * 处理用户在命令行里敲的 `systemwin language` 这条命令。
 *
 * 具体来说，它要干两件截然不同的事情（大家注意，这两件事的区别很重要！）：
 *   1) 如果用户只是敲了 `systemwin language`，后面什么都没有跟，
 *      那意思就是“我想看看当前程序到底支持哪些语言”，
 *      所以这时候我们就要把所有的语言列表打印出来给用户看；
 *   2) 如果用户敲了 `systemwin language 中文` 或者 `systemwin language en`
 *      这种带参数的写法，那意思就是“我想把程序的界面语言切换成中文/英文”，
 *      所以这时候我们就要真正地去执行切换语言这个动作。
 *
 * 为什么要把这个功能单独拆成一个类呢？因为整个程序采用了“命令模式”
 * （Command Pattern）的设计：每一个命令（language、help、version……）都是一个
 * 独立的类，它们都实现了同一个 Command 接口（interface），
 * 然后统一由命令分发器（dispatcher）根据用户敲的第一个单词来决定调用哪个类。
 * 这样做的好处是：代码结构清晰、每个类只管自己的事情、以后想加新命令
 * 只需要新写一个类然后注册一下就行，完全不用去改动别的命令的代码。
 *
 * 另外请大家注意类前面的关键字：`public final class`。
 * final 的意思是“这个类不能被继承”，也就是说不允许别人再去写一个
 * `class MyLanguageCommand extends LanguageCommand` 来扩展它。
 * 这是因为这个类的功能已经完整了，没有必要再被继承，
 * 标记成 final 可以防止别人乱改乱继承，保证程序行为稳定。
 *
 * 还有 implements Command 这个语法：表示“我承诺实现 Command 接口里规定的
 * 所有方法”。Command 接口里规定了一个 run(Args args) 方法，
 * 所以下面我们就能看到 run 方法，它是整个命令的“入口点”。
 * ============================================================================
 */
public final class LanguageCommand implements Command {

    // ==========================================================================
    // 【成员变量 ctx 的中文解释】
    // ==========================================================================
    // 这个 ctx 是 CommandContext 类型，全称是 Command Context，即“命令上下文”。
    // 什么叫“上下文”呢？可以把它理解成一个“装满各种工具和资料的小背包”，
    // 在命令执行的过程中，如果我们需要用到程序的某些全局信息
    // （比如：国际化消息资源、当前工作目录、配置对象等），
    // 就可以直接从这个小背包里拿，而不需要自己再去新建一个。
    //
    // 为什么要用 ctx.i18n 来取消息，而不是直接写死字符串呢？
    // 因为程序是支持多语言的（这正是本命令存在的意义！）。
    // 比如提示语“当前语言是中文”，在中文环境下应该显示中文，
    // 在英文环境下应该显示英文。如果我们把字符串直接写死在代码里，
    // 那就没法翻译了。所以正确做法是：通过 ctx.i18n.msg("xxx") 这种形式，
    // 传进去一个“消息的键”（key，类似字典里的词条编号），
    // 由 i18n 模块根据当前用户选定的语言，自动翻译成对应的文字。
    // 这就是“国际化”（internationalization，缩写 i18n）的基本思想。
    //
    // 大家现在可能觉得这个设计有点绕，但请记住：在真实的工程项目里，
    // 把“文本内容”和“代码逻辑”分开管理，是一种非常常见且重要的做法！
    // ==========================================================================
    private final CommandContext ctx;

    // ==========================================================================
    // 【构造方法的中文解释】
    // ==========================================================================
    // 这是一个构造函数（constructor），它的名字必须和类名完全一样，
    // 也就是 LanguageCommand。它的作用很简单：在创建本命令对象的时候，
    // 把外界传入的 CommandContext 保存到上面的成员变量 ctx 里，方便以后使用。
    //
    // 为什么不在 run 方法里再传 ctx 呢？因为命令分发器在创建命令对象的时候
    // 就已经知道上下文是什么了，把 ctx 通过构造函数传进来，
    // 可以让这个命令对象“自带上下文”，run 方法里就不用再传参了，
    // 用起来更顺手，也更符合命令模式“每个命令自己准备好一切”的风格。
    //
    // 大家注意：这里使用 this.ctx = ctx; 这种写法，就是为了区分
    // “左边的成员变量 ctx”和“右边的参数 ctx”，避免名字冲突，
    // this 指的就是“当前这个对象自己”。
    // ==========================================================================
    public LanguageCommand(CommandContext ctx) {
        this.ctx = ctx;
    }

    // ==========================================================================
    // 【run 方法的中文解释——命令执行的真正入口】
    // ==========================================================================
    // @Override 这个注解（annotation）的意思是：告诉编译器，
    // “我这个方法是对接口/父类中已有方法的覆写（override）”。
    // 也就是说，Command 接口里已经声明了 run(Args) 这个方法，
    // 现在我在这个类里给出它的具体实现。
    // 如果接口里根本没有这个方法，或者签名对不上，编译器会直接报错，
    // 这能在编译期就帮我们抓住很多低级错误，所以一定要记得写 @Override。
    //
    // run 方法接收一个 Args 类型的参数，它就是用户敲下的整条命令行参数。
    // 比如用户敲了 `systemwin language en`，那么 Args 里就会装着
    // ["language", "en"] 这样的内容（其中的 "en" 就是所谓的“位置参数”
    // positional argument）。
    //
    // 方法返回 int（整数），这是命令模式的一个约定：
    //   返回 0 表示命令执行成功；
    //   返回非 0（比如 1）表示执行过程中出了错误。
    // 这样上层代码（比如主程序）就可以根据返回值判断命令有没有成功，
    // 甚至可以决定进程的退出码（exit code），非常实用。
    //
    // 整个方法的逻辑可以概括成一句话：
    // “先看看用户有没有给参数：没给参数就列出所有语言；给了参数就尝试切换语言。”
    // 接下来我们就一行一行地看具体代码。
    // ==========================================================================
    @Override
    public int run(Args args) {
        // ----------------------------------------------------------------------
        // 【第一个分支：用户没有给任何参数的情况（即只敲了 systemwin language）】
        // ----------------------------------------------------------------------
        // args.positional 是一个列表（List），里面装着用户在命令后面输入的
        // “位置参数”。什么是位置参数呢？就是不看选项名、只看先后顺序的参数。
        // 比如 `systemwin language en` 里，"en" 就是第 0 个位置参数。
        //
        // .isEmpty() 就是判断这个列表是不是空的。
        // 如果列表是空的，就说明用户只敲了 `systemwin language`，
        // 后面什么参数都没有跟，那我们就把“列出所有可用语言”当作默认行为。
        // 这种“无参数时给一个友好的默认行为”的设计在命令行工具里非常常见，
        // 就好比你敲 `help` 不带任何参数，它就会把帮助信息显示出来一样。
        if (args.positional.isEmpty()) {
            // 先打印一个标题（比如“可用语言列表”之类的字样）。
            // 注意：我们没有直接写死中文或英文的标题字符串，
            // 而是用 ctx.i18n.msg("lang.header") 去取。
            // "lang.header" 就是这个消息在资源文件里的键（key），
            // i18n 模块会根据当前语言自动把它翻译成对应的文字，
            // 这样同一个程序在中文系统上显示中文、在英文系统上显示英文。
            System.out.println(ctx.i18n.msg("lang.header"));

            // 获取“当前正在使用的语言代码”。语言代码就是类似 "zh"、"en"、
            // "ja" 这种两个字母的简称（也有可能是带地区后缀的，比如 "zh-CN"）。
            // 我们把它单独存到一个变量 current 里，
            // 因为在下面循环打印每一种语言的时候，都要拿它和当前语言做比较，
            // 以便给“当前正在使用的语言”打上一个特殊的标记（比如加个星号或"（当前）"）。
            // 提前把值存进变量，循环里就不用重复调用方法了，代码更清晰也稍微快一点。
            String current = ctx.i18n.currentLanguage();

            // 这是一个 for-each 循环，也就是“增强 for 循环”。
            // availableLanguages() 会返回程序支持的所有语言代码的集合/列表，
            // 比如 ["en", "zh", "ja", "fr"]。循环每走一圈，
            // 变量 code 就会依次变成其中一个语言代码，
            // 这样我们就能把每种语言都处理一遍，把列表完整地打印出来。
            for (String code : ctx.i18n.availableLanguages()) {
                // 光有语言代码（比如 "en"）用户看不懂，最好再显示一个
                // “人类可读的显示名”（比如 "English"、"中文"、"日本語"）。
                // languageDisplayName(code) 干的就是这件事：
                // 传入语言代码，返回它对应的显示名称。
                // 这里为什么要单独再调一次呢？因为显示名和代码是两码事，
                // 代码是程序内部用的标识符，显示名才是给用户看的文字。
                String name = ctx.i18n.languageDisplayName(code);

                // 下面这行是整个循环里最核心的判断逻辑，我们拆开来看：
                // code.equals(current) 表示“这次循环拿到的语言代码，
                // 是不是等于当前正在使用的语言代码”。
                // 注意：这里用的是 .equals() 而不是 ==，
                // 因为 String（字符串）是对象，== 比较的是“是不是同一个对象”
                // （引用地址），而 .equals() 才是真正比较“内容是否一样”。
                // 初学者最容易在这里踩坑，请务必记住：
                // 比较字符串内容，永远用 equals()！
                //
                // 这是一个三元运算符（ternary operator）表达式：
                //   条件 ? 值1 : 值2
                // 它的意思是：如果条件成立，整个表达式就等于值1；
                // 如果条件不成立，就等于值2。它其实就是 if/else 的简写形式。
                // 在这里：如果 code 是当前语言，就用 "lang.current" 这个键
                // 来生成一行“这是当前语言”的提示（比如“当前语言：中文 (zh)”）；
                // 否则就用 "lang.entry" 这个键来生成一行普通的列表条目
                // （比如“中文 (zh)”）。
                // 为什么要区分这两种情况呢？因为用户看列表的时候，
                // 一眼就能看出“我现在用的是哪个”，体验会好很多。
                //
                // 至于 msg("lang.current", code, name) 后面跟着的
                // code 和 name 这两个参数，则是消息模板里的占位符：
                // 资源文件里的模板可能是“当前语言：{1} ({0})”这样的格式，
                // 我们把 code 和 name 传进去，i18n 模块会替我们填好这些空位，
                // 生成完整的句子。这样模板和内容分离，翻译起来就非常方便。
                String line = code.equals(current)
                        ? ctx.i18n.msg("lang.current", code, name)
                        : ctx.i18n.msg("lang.entry", code, name);

                // 打印这一行。前面加两个空格 "  " 是为了缩进，
                // 让每一行语言条目都往右缩进一点，
                // 这样输出出来的列表会更有层次感，看起来更整齐美观。
                System.out.println("  " + line);
            }
            // 列表打印完毕，一切顺利，按照命令模式的约定返回 0 表示成功。
            return 0;
        }

        // ----------------------------------------------------------------------
        // 【第二个分支：用户给了参数的情况（即敲了 systemwin language xxx）】
        // ----------------------------------------------------------------------
        // 能走到这里，说明 args.positional 不是空的，
        // 也就是说用户确实输入了一个语言代码，想要切换语言。
        // 下面用 try/catch 把“切换语言”的动作包起来，这是为什么呢？
        // 因为用户输入的语言代码可能是乱写的（比如敲了个不存在的 "xyz"），
        // 或者配置文件出问题了、写不进去等等，这些情况都可能抛出异常（Exception）。
        // 如果异常不处理，程序就会崩溃退出，用户会看到一堆可怕的红色报错堆栈。
        // 所以我们用 try/catch 把可能出错的代码保护起来，
        // 一旦出错，就抓住异常，给用户打印一句友好的错误提示，
        // 然后返回 1（表示失败了），让程序体面地收场，而不是直接崩溃。
        // 这种“把可能失败的代码包在 try/catch 里，失败时给出友好提示”
        // 的做法，是编写健壮程序（robust program）的基本功。
        try {
            // 用户输入的第 0 个位置参数（即 args.positional.get(0)）
            // 就是他想切换成的语言代码，把它传给 I18n.switchLanguage 方法。
            // 注意：switchLanguage 是一个静态方法（static），
            // 所以我们不是通过某个对象去调用它，而是直接通过类名 I18n 调用。
            // 静态方法的意思是“这个操作属于整个类，不依赖某个具体对象”。
            //
            // 这个方法会做几件事：检查这个语言代码是否受支持，
            // 如果支持，就更新当前语言，并把选择持久化保存到配置文件里
            // （%APPDATA%\SystemWin\config.properties，这样下次启动程序时
            // 仍然是用户选择的语言）；如果不受支持，就会抛出异常，
            // 被下面的 catch 捕获并处理。
            //
            // 方法的返回值是一个新的 I18n 对象（这里叫 switched），
            // 它是“切换完成之后”的国际化实例。
            // 为什么要用切换后的新实例，而不是继续用 ctx.i18n 呢？
            // 因为语言切换之后，当前语言已经变了，
            // 后续所有消息都应该按新语言来翻译，
            // 所以我们要用 switched 来发消息、查当前语言，
            // 这样才能确保打印出来的提示是“新语言”而不是“旧语言”。
            // 这是一个非常容易忽略的细节，请大家留意。
            I18n switched = I18n.switchLanguage(args.positional.get(0));

            // 打印切换成功的提示消息，比如“已切换到中文 (zh)”。
            // 大家看，这里传入的参数是 switched.currentLanguage() 和
            // switched.languageDisplayName(...)，也就是从“切换后的实例”
            // 里去取当前语言代码和显示名，正好呼应了上面说的那个细节。
            System.out.println(switched.msg("lang.switched",
                    switched.currentLanguage(),
                    switched.languageDisplayName(switched.currentLanguage())));

            // 再打印一条“语言选择已被保存，下次启动时生效”之类的提示
            // （消息键是 "lang.persisted"，persisted 就是“已持久化”的意思，
            // 所谓持久化，就是把数据保存到磁盘上，程序退出再启动也不会丢）。
            System.out.println(switched.msg("lang.persisted"));

            // 切换流程顺利走完，返回 0 表示成功。
            return 0;
        } catch (Exception e) {
            // 只要上面 try 块里任何一行代码抛出了异常，程序就会跳到这个
            // catch 块来执行。变量 e 就是被捕获到的那个异常对象。
            //
            // 这里用 e.getMessage() 取出异常里携带的、人类可读的错误描述
            // （比如“不支持的语言代码：xyz”），然后直接打印给用户看。
            // 注意：这里打印的是 e.getMessage() 而不是整个异常堆栈，
            // 因为对普通用户来说，堆栈信息（stack trace）太长太吓人了，
            // 只显示一句简洁的错误原因体验更好。
            // （当然，如果是调试程序，我们通常还会把完整的堆栈打出来，
            // 这里就省略了。）
            System.out.println(e.getMessage());
            // 出错了，按照命令模式的约定返回 1 表示执行失败。
            // 上层代码可以根据这个返回值知道“语言切换没有成功”。
            return 1;
        }
    }
}
