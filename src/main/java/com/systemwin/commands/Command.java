// =====================================================================================
// 这个文件是整个 SystemWin 项目里"命令（Command）"这个概念的定义所在。
// 先别急，我们慢慢来，把这里的每一行都掰开揉碎了讲清楚，
// 保证你一个刚入门的新手也能看懂这段代码到底在干什么、为什么这么写。
//
// 首先，第 1 行的 package 声明：
// "package com.systemwin.commands;" 这句话的意思是：把当前这个 Java 文件
// 归类到 com.systemwin.commands 这个"包（package）"里面。
// 包，你可以把它理解成一个文件夹、一个抽屉，专门用来把功能相近的类放在一起管理。
//
// 那这样做有什么好处呢？主要有三点：
//   1. 避免类名冲突：不同包里可以有同名的类，互不干扰、井水不犯河水；
//   2. 便于组织管理：几百个类堆在一起谁也找不到，分门别类才好维护才好找；
//   3. 控制访问权限：包与包之间可以设置谁能看到谁，保护内部实现不被乱用。
//
// 总之，package 就是 Java 世界里整理代码的"收纳盒"，把乱七八糟的东西归归类。
// 而我们这个包（commands 包）里放的，全都是跟"命令"有关的家伙们：
// 比如 StartCommand（启动命令）、StatusCommand（状态命令）、
// CommandRegistry（命令注册表，负责把名字和命令对应起来）等等。
// =====================================================================================
package com.systemwin.commands;

import com.systemwin.cli.Args;

// 这一行是 import（导入）语句：
// "import com.systemwin.cli.Args;" 的意思是：我们要用到 cli 包
// （也就是 com.systemwin.cli 这个包）里面的 Args 这个类。
//
// 为什么要写 import？因为 Java 里每个类都有自己的"全名"，
// 全名 = 包名 + 类名，比如这里说的就是 com.systemwin.cli.Args。
// 如果不写 import 的话，我们在下面的代码里就得每次都写完整的全名，
// 那多麻烦、多啰嗦啊！所以 Java 提供了 import 这种"偷懒"的写法：
// 只要在文件开头声明一次，后面就可以直接用简短的类名 Args 了，
// 代码读起来也清爽很多。
//
// 那 Args 到底是干什么的？看名字就能猜个八九不离十，
// 它是"参数（Arguments）"的意思，也就是用户在命令行里输入的那一串东西
// （比如 systemwin start --force 这样的命令后面跟着的内容）。
// Args 类会把命令行里输入的参数整理成一个个方便读取的对象，
// 这样命令实现类（也就是实现 Command 接口的那些类）就能知道
// 用户到底想干什么、还带上了哪些选项，从而决定自己该怎么做。
// 这一点很重要，等一会儿看到 run 方法的参数时，你就能体会到它的用处了。

/**
 * A single systemwin command (start, status, install, language, ...).
 *
 * 上面这行英文注释的意思是：
 * "一个独立的 systemwin 命令（比如 start、status、install、language 等等）。"
 *
 * 也就是说，Command 这个接口，就代表了"一条命令"本身。
 * systemwin 这个程序在启动之后，会先看看用户在命令行里敲的是哪个命令，
 * 然后通过 CommandRegistry（命令注册表）找到对应的、实现了这个接口的类，
 * 再让那个类去干活。命令和命令之间是相互独立的，
 * 你启动你的 start，我干我的 status，互不打扰。
 *
 * 看到这里你可能要问了：为什么要用接口（interface），
 * 而不是直接定义一个普普通通的类呢？
 * 这里藏着一个很重要的设计思想，叫做"面向接口编程"，
 * 我们一条一条地讲：
 *
 *   1. 统一规范：不管是什么命令（启动、查状态、安装、改语言……），
 *      它们都必须提供 run 这个方法。这样一来，调用方（框架代码）
 *      就可以用完全相同的方式去调用每一条命令，
 *      完全不用去区分你是 start 还是 status 还是 install。
 *      对调用方来说，它们长得都一样，都会 run，这就够了。
 *
 *   2. 灵活扩展：以后要新增一条命令（比如 systemwin uninstall 卸载命令），
 *      我们只需要新写一个类，让它 implements Command（实现这个接口），
 *      再把 run 方法认认真真实现一遍就行了，
 *      完全不用去改动其他已有的代码。这就是软件工程里常说的
 *      "开闭原则"：对扩展开放，对修改关闭。
 *
 *   3. 解耦：命令的具体实现细节（每个命令内部是怎么一步步做的）
 *      和调用方式（框架怎么使用命令）被分开了，
 *      两边可以各自独立地演化，谁都不用迁就谁。
 *
 * 简单打个比方：Command 接口就像一张"合同"，或者说一张"招聘启事"，
 * 上面清清楚楚写着："凡是自称命令的家伙，都必须会 run 这一招。"
 * 至于每个命令是怎么施展 run 的、内部是绕了三个弯还是走了直线，
 * 接口一概不关心，完全由各个实现类自己去发挥、自己去实现。
 */
public interface Command {

    /**
     * Runs the command; returns the process exit code.
     *
     * 上面这行英文注释的意思是：
     * "运行这条命令，并返回进程的退出码。"
     *
     * 这句话信息量很大，我们把它拆开一点点地看：
     *
     * （一）方法名 run：
     * 这就是执行命令的入口方法，是命令真正干活的地方。
     * 不管是 start、status 还是 install，最后框架都会调用这个方法，
     * 让命令去完成它该完成的事情。
     * 注意：这里是接口，所以只有方法的"声明"（签名），
     * 没有方法体（没有那一对大括号和里面的语句）。
     * 真正的"怎么做"，要等实现类（比如 StartCommand、StatusCommand）
     * 去把 run 方法的身体补全。接口只负责规定"长什么样"，不负责"怎么干"。
     *
     * （二）返回类型 int：
     * 这个方法返回的是一个 int（整数），也就是"退出码（exit code）"。
     * 退出码是程序向操作系统"汇报结果"的一种非常传统的方式：
     *   - 返回 0：通常表示一切正常，命令执行成功了；
     *   - 返回非 0（比如 1、2、3……）：表示执行过程中出了某种问题，失败了。
     * 为什么非要返回这么一个小整数呢？因为 systemwin 常常会被脚本
     * （比如 .bat 批处理文件或者 .sh 脚本）调用，
     * 脚本需要根据退出码来判断"刚才那条命令到底成没成功"，
     * 然后决定下一步该怎么做。所以这个返回值虽然只是一个小小的整数，
     * 却是程序与程序之间相互沟通的一座重要桥梁，可千万不能小看它。
     *
     * （三）参数 Args args：
     * 名字叫 args，类型是 Args，也就是上面 import 进来的那个类。
     * 它装着用户在命令行输入的全部参数和选项，
     * 命令实现类就从这里读取自己需要的信息。
     * 比如 start 命令可能需要知道"要不要强制重启"，
     * 这个信息就藏在 args 里面。
     * 注意这里参数类型用的是 Args 而不是 String[]，
     * 说明项目对命令行参数做了一层封装，用起来更舒服、更不容易出错，
     * 也体现了"不要让底层细节到处乱飞"的封装思想。
     *
     * （四）throws Exception：
     * 这一句声明了"这个方法可能会抛出异常"。什么意思呢？
     * 就是提前告诉调用者：我这个方法在运行过程中可能会出错
     * （比如文件不存在、权限不够、服务起不来、端口被占用等等），
     * 出错的时候我不会自己偷偷吞掉，而是会把这个错误"抛"出来，
     * 交给上层去处理。这是 Java 里一种很常见的错误处理约定：
     * "我负责发现问题，你负责决定怎么善后"。
     * 这样一来，实现类在 run 里面就可以放心大胆地写可能出错的代码，
     * 不用每句话都包一层 try-catch，代码会干净很多。
     *
     * 最后总结一下：Command 接口非常简单，一共就只有一个 run 方法，
     * 但这正是整个命令体系的"地基"——所有命令都要从这里出发。
     * 看懂了这个接口，再去看那些实现类（比如 StartCommand、StatusCommand、
     * InstallCommand 等）就会觉得豁然开朗，因为它们本质上都只是在回答
     * 同一个问题："当用户叫我执行的时候，我到底该怎么做？"
     * 好了，这个文件就讲到这里，是不是感觉没那么难了？
     */
    int run(Args args) throws Exception;
}
