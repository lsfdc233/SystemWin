package com.systemwin.commands;

// ============================================================================
// 文件头说明（废话开始）：
// 这个文件是 StatusCommand，也就是 systemwin 命令行工具里的"状态"子命令。
// 用户敲下 "systemwin status" 之后，命令行框架会创建一个 StatusCommand 对象，
// 然后调用它的 run() 方法，把用户从终端上输入的参数（args）传进来。
// 简单来说，这个类的职责就一句话：查一下 Windows 服务现在的状态，然后打印给用户看。
// 它自己不直接跟 Windows 打交道，真正去调用 Windows API 查询服务信息的是
// WindowsServiceManager 这个工具类，这里只是负责把查到的结果整理成好看的文字。
// 所以大家可以把 StatusCommand 想象成"前台接待员"：
// 前台接待员（本类）负责把客人的问题（用户输入）翻译成内部请求，
// 然后转身去问后面的办事人员（WindowsServiceManager），
// 再把办事人员回答的内容（ServiceInfo 对象）翻译成客人能看懂的话（中文提示）打印出来。
// 下面的每一个方法、每一个判断，我们都会用大白话再解释一遍，力求让一个
// 从来没看过这段代码的新人，也能从头到尾读明白每一行到底在干什么、为什么这么写。
// ============================================================================

import com.systemwin.cli.Args;
import com.systemwin.service.ServiceInfo;
import com.systemwin.service.WindowsServiceManager;
import com.systemwin.util.Units;

import java.time.OffsetDateTime;
import java.time.format.DateTimeFormatter;
import java.time.format.DateTimeParseException;
import java.util.List;

/**
 * {@code systemwin status [unit...]} shows service status; with no unit it
 * prints a system summary.
 */
// ----------------------------------------------------------------------------
// 上面的英文 javadoc 翻译成中文就是：
// "systemwin status [unit...]" 这个命令用来显示服务的状态；
// 如果后面没有带任何 unit（服务单元名）参数，那就打印一份系统的总体摘要。
// 也就是说，这个命令有两种用法，像变形金刚一样有两种形态：
//   形态一：直接敲 "systemwin status"，后面什么都不跟 —— 这时候它去列出系统里
//           所有已知的服务，统计一下一共有多少个，然后打印一个"总览"。
//   形态二：在 status 后面跟上一个或多个服务单元名，比如
//           "systemwin status mysql nginx" —— 这时候它就一个一个地去查
//           这些服务各自的详细状态，比如启动模式是什么、现在活没活着、
//           进程号（PID）是多少、从什么时候开始运行的，等等。
// 类名里的 final 关键字表示这个类不允许被继承，是"最终版本"；
// "implements Command" 表示它实现了 Command 这个接口（接口就是一份"合同"，
// 合同里规定：凡是自称是命令的类，都必须提供一个 run(Args) 方法来执行自己）。
// 这样命令行框架就可以统一地调用所有命令，不用关心每个命令内部是怎么实现的，
// 这就是面向接口编程的好处——框架只看"合同"，不看"人"。
// ----------------------------------------------------------------------------
public final class StatusCommand implements Command {

    // ------------------------------------------------------------------------
    // 下面这个 DISPLAY_TIME 是一个"格式化器"对象，它是 static final 的：
    //   static 意味着它属于这个类本身，而不是属于某个具体的 StatusCommand 实例，
    //           也就是说无论创建多少个 StatusCommand 对象，大家共享同一个格式化器，
    //           没有必要每个对象都重新造一个（造格式化器也是要花钱花时间的）。
    //   final 意味着它一旦被赋值，就永远不能再改了，防止有人不小心把它换掉。
    // 它干的事情是把一个"带时区的时间"（OffsetDateTime）格式化成我们人类
    // 看着最顺眼的字符串："yyyy-MM-dd HH:mm:ss"，比如 "2024-01-15 09:30:45"。
    // 之所以要单独抽一个格式化器放在字段里，而不是每次用的时候临时
    // DateTimeFormatter.ofPattern(...) 现造一个，是因为"造格式器"本身有开销，
    // 而且这个格式在程序里到处都要用，抽出来定义一次，既省事又不会写错格式串。
    // 有人可能会问：为什么不用更简单的时间类型呢？因为 Windows 服务返回的
    // 启动时间是一个带时区的 ISO 字符串（比如 2024-01-15T09:30:45+08:00），
    // 这种字符串必须用 OffsetDateTime 才能正确解析，所以这里配套用了它。
    // ------------------------------------------------------------------------
    private static final DateTimeFormatter DISPLAY_TIME =
            DateTimeFormatter.ofPattern("yyyy-MM-dd HH:mm:ss");

    // ------------------------------------------------------------------------
    // ctx 是 CommandContext，也就是"命令上下文"。它是这个命令的"后勤大管家"：
    // 里面装着这个命令干活时需要的各种依赖，比如：
    //   ctx.services —— 服务查询器，用来按名字查服务信息（返回 ServiceInfo）；
    //   ctx.i18n     —— 国际化的消息表，所有要打印给用户看的文字都从这里取，
    //                   这样以后要翻译成别的语言，只需要改消息表，不用改代码。
    // 为什么要把这些东西塞进一个 ctx 传进来，而不是在类里 new 一个呢？
    // 这叫"依赖注入"：对象自己不负责造依赖，而是由外面的人（框架）把依赖递给它。
    // 好处是方便测试——测试的时候可以塞一个假的、专门用于测试的 services，
    // 不用真的去查 Windows 服务；同时也方便替换实现，代码耦合度低。
    // ------------------------------------------------------------------------
    private final CommandContext ctx;

    // ------------------------------------------------------------------------
    // 构造函数。所谓构造函数就是"对象出生时自动执行的那段初始化代码"。
    // 当框架执行 new StatusCommand(ctx) 的时候，Java 会自动调用这个构造方法，
    // 把传进来的 ctx 存到上面那个私有字段里，方便后面 run() 方法使用。
    // 这里没有任何复杂的逻辑，就是一个"交接"动作：你给我的，我收好。
    // ------------------------------------------------------------------------
    public StatusCommand(CommandContext ctx) {
        this.ctx = ctx;
    }

    // ------------------------------------------------------------------------
    // @Override 注解的意思是："我重写了父接口里声明的方法"。
    // 写上这个注解有两个好处：
    //   1. 给阅读代码的人看——一眼就知道这个方法是接口规定的"标准入口"；
    //   2. 给编译器看——如果方法签名写错了（比如参数类型不对），编译器会直接报错，
    //      防止我们自以为重写了接口方法、实际上写了个无关的新方法。
    // run() 是 Command 接口规定的"执行入口"，命令行框架解析完用户输入后，
    // 就会调用这个方法。返回值是一个整数，表示命令执行后的退出码：
    //   0 表示一切正常；非 0 表示出问题了，框架会把这个数字当作进程退出码，
    // 这样在批处理脚本（比如 .bat 或 PowerShell）里就可以用 %ERRORLEVEL%
    // 或者 $LASTEXITCODE 判断命令到底成没成功。
    // 整个 run() 的流程可以概括成一句话：先看有没有参数，没有参数就打印总览，
    // 有参数就挨个查每个服务的状态，最后把退出码交还给框架。
    // ------------------------------------------------------------------------
    @Override
    public int run(Args args) {
        // args.positional 是用户在命令行上输入的"位置参数"列表。
        // 什么叫位置参数？就是不带任何选项前缀（如 -x / --xxx）的裸参数。
        // 比如 "systemwin status mysql" 里的 "mysql" 就是一个位置参数。
        // .isEmpty() 就是判断这个列表是不是空的。
        // 如果列表是空的，说明用户只敲了 "systemwin status"，没指定任何服务，
        // 那我们就走"总览"分支（形态一）。
        if (args.positional.isEmpty()) {
            // ctx.services.list() 去把所有已知的服务都列出来，得到一个列表。
            // 注意：这里只是"列出"所有服务的名字/基本信息，并不会真的去
            // 挨个查询每个服务的实时状态——那样太慢了，总览嘛，知道个数就够了。
            List<ServiceInfo> all = ctx.services.list();
            // 从 i18n 消息表里取出 "status.summary" 这条消息模板，
            // 把服务总数 all.size() 填进去，然后打印。
            // 打印出来的效果大概类似于："发现 5 个已注册的服务。"之类的话。
            System.out.println(ctx.i18n.msg("status.summary", all.size()));
            // 接着打印 "status.hint" 这条提示消息，一般是提醒用户：
            // "想知道某个服务的详情？在 status 后面跟上服务名试试。"
            // 这种"用完再给个提示"的设计，对新手用户特别友好，
            // 免得用户拿到工具之后一脸茫然不知道该敲什么。
            System.out.println(ctx.i18n.msg("status.hint"));
            // 总览分支一切顺利，返回退出码 0，表示成功。
            return 0;
        }
        // 走到这里，说明用户至少指定了一个服务名，进入"逐个查询"分支。
        // code 变量用来记录"目前为止遇到的最严重的错误码"。
        // 为什么初始值是 0 而不是别的？因为 0 表示"没有错误"，
        // 先假定一切顺利，如果后面查询某个服务时出错了，再把错误码记下来。
        int code = 0;
        // 用 for 循环遍历用户输入的每一个服务单元名。
        // 这里为什么用"增强 for"而不是带下标的 for？因为这里我们只需要
        // 依次处理每个元素，根本不需要知道元素在列表里的位置（下标），
        // 增强 for 更简洁、更不容易写错，可读性也更好。
        for (String unit : args.positional) {
            // 对当前这个服务名调用 statusOne() 去查询并打印它的详细状态，
            // 拿到这次查询的退出码 c。c 为 0 表示这个服务查得顺顺利利。
            int c = statusOne(unit);
            // 如果这次查询返回了非 0 的退出码（比如服务没找到，返回 4），
            // 就把 code 更新成这个错误码。注意这里的判断是 c != 0，
            // 也就是说一旦出现错误，后面 code 就被"污染"成非 0 了，
            // 即使后面几个服务都查成功了，整个命令最终也会以失败收场。
            // 这正是我们想要的行为：只要有一个服务查不到，命令就算失败，
            // 脚本里就能通过退出码发现"刚才那次批量查询里有问题"。
            if (c != 0) {
                code = c;
            }
            // 注意：这里没有 break，也就是说即使第一个服务就报错了，
            // 我们依然会继续查询剩下的服务，把每个服务的结果都打印出来。
            // 这是刻意为之的：用户一次性问了多个服务，我们希望尽量
            // "有始有终"地把每个都答复完，而不是遇到一个错误就半途而废，
            // 让用户一次只看到一条错误、修完再来一次。
        }
        // 循环结束后，把最终记录的退出码返回给框架。
        // 如果一切正常，这里就是 0；如果中途有任何服务出错，这里就是非 0。
        return code;
    }

    // ------------------------------------------------------------------------
    // statusOne 是这个类里真正干细活儿的"小工"，负责查询并打印"一个"服务的状态。
    // 参数名叫 rawUnit，注意"raw"（原始）这个前缀——它暗示这个参数是
    // 用户原封不动敲进来的字符串，还没有经过任何规范化（normalize）处理。
    // 为什么要把"规范化"单独做一步呢？因为用户输入很随意，比如：
    //   可能是 "MYSQL"（全大写），也可能是 "mysql"（全小写），
    //   可能是 "mysql.exe"，也可能是 "C:\Program Files\MySQL\bin\mysqld.exe"，
    //   甚至可能带前后空格（" mysql "）。
    // Windows 服务注册表里存的名字格式是固定的，如果不把用户输入统一成
    // 标准格式就去查，大概率会查不到。所以先交给 Units.normalize() 洗一遍，
    // 这就是下面第一行的目的。
    // 这个方法返回 int 退出码，规则跟 run() 里一致：0 表示成功，非 0 表示失败。
    // ------------------------------------------------------------------------
    private int statusOne(String rawUnit) {
        // 第一步：规范化。把用户输入的原始字符串交给 Units.normalize() 处理，
        // 得到标准的、干干净净的服务单元名，存进 unit 变量。
        // 具体的规范化规则（大小写、去空格、去 .exe 后缀等）都在 Units 工具类里，
        // 这里只需要调用，不用关心内部实现——这就是"封装"的思想：
        // 复杂的事情交给专门的类去办，调用方只负责说"我要标准格式"。
        String unit = Units.normalize(rawUnit);
        // 第二步：从"单元名"推导出"服务名"。
        // 这里要解释一下 unit 和 name 的区别：在 systemwin 的世界观里，
        // "单元"（unit）是用户层面看到的名字，而"服务名"（serviceName）才是
        // Windows 服务管理器（SCM）真正用来标识服务的那个名字。
        // 比如用户习惯叫它 "mysql"，但 Windows 里注册的服务名可能是 "MySQL80"，
        // 或者反过来。Units.serviceName() 就是负责这两个名字之间的换算的。
        // 之所以要分两层，是为了让用户不用记住 Windows 内部那些又长又怪的
        // 注册名，只要用自己顺口的单元名就行，换算的麻烦事由工具内部消化。
        String name = Units.serviceName(unit);
        // 第三步：真正去查询服务信息。ctx.services.query(name) 拿着服务名
        // 去查 Windows，返回一个 ServiceInfo 对象，里面装着这个服务的各种
        // 信息：显示名、启动模式、当前状态、进程号、启动时间、可执行文件路径等。
        // 如果查不到（比如用户拼错了名字），query 会返回 null。
        ServiceInfo info = ctx.services.query(name);
        // 第四步：判断服务是否存在。info == null 就意味着没查到。
        if (info == null) {
            // 没找到！从消息表里取出 "status.notfound" 这条消息，
            // 把用户输入的那个单元名填进去，打印一条友好的"查无此服务"提示。
            // 注意这里打印的是 unit（规范化后的名字）而不是原始输入 rawUnit，
            // 这样用户看到的提示里是"标准写法"，以后照着敲就不会再错了，
            // 也算是一种隐性的"教学"。
            System.out.println(ctx.i18n.msg("status.notfound", unit));
            // 返回退出码 4。为什么是 4 而不是别的数字？
            // 这是命令行工具的惯例：不同的错误码代表不同的错误类型，
            // 4 在这里表示"资源/服务不存在"这一类错误，方便脚本精确判断
            // 失败原因。这个数字是设计者定下的约定，写注释说明一下，
            // 免得后人看着一个魔法数字 4 摸不着头脑。
            return 4;
        }
        // 第五步：决定"显示名"。Windows 服务有一个"显示名"（displayName），
        // 是给人看的友好名称，通常比内部服务名更可读，比如
        // "MySQL80" 的显示名可能是 "MySQL80" 或者 "MySQL Server"。
        // 但有些服务在注册时可能没有设置显示名，或者显示名是空字符串，
        // 这时候如果我们硬要打印显示名，就会打印出一行空白，很难看。
        // 所以这里用了一个三元表达式（? :）做兜底：
        //   如果 displayName 是 null（根本没设置）或者 isEmpty()（设置了但内容是空的），
        //   就退而求其次，用内部的 name 来充当显示名；
        //   否则就用真正的 displayName。
        // 这种"主选不行就换备选"的写法在处理外部数据时非常常见，
        // 因为外部系统给的数据永远不能假设它是齐全的、规范的。
        String display = (info.displayName() == null || info.displayName().isEmpty())
                ? info.name()
                : info.displayName();
        // 第六步：打印状态信息的"头部"那一行。
        // 从消息表取 "status.header" 模板，把单元名 unit 和显示名 display
        // 都填进去。打印出来大概长这样：
        //   "- mysql.service - MySQL Server" 或者 "状态：mysql（MySQL Server）"
        // 具体长什么样取决于消息表里模板的写法，这里只负责传参数。
        System.out.println(ctx.i18n.msg("status.header", unit, display));

        // 第七步：打印"加载/装载"信息这一行。
        // WindowsServiceManager.enableState(info.startMode()) 把服务的"启动模式"
        // 翻译成人类语言。启动模式（startMode）是 Windows 里一个比较底层的东西，
        // 可能的值包括：AUTO_START（开机自启）、DEMAND_START（手动启动）、
        // DISABLED（已禁用）等。这个原始值直接打印给用户看会非常不友好，
        // 所以这里通过 enableState() 把它转换成"自动/手动/禁用"这类易懂的词。
        String start = WindowsServiceManager.enableState(info.startMode());
        // 服务可执行文件的路径：info.path() 可能为 null（有些服务不报告路径），
        // 如果直接拿去拼字符串，就会在输出里出现 "null" 字样，很难看，
        // 所以这里用三元表达式兜底：null 就换成空字符串 ""。
        String path = info.path() == null ? "" : info.path();
        // 把启动模式和路径拼在一起（中间用 "; " 分隔），填进 "status.loaded"
        // 模板里打印。这一行的作用相当于告诉用户："这个服务已经被系统加载了，
        // 它的启动方式是 XXX，它的可执行文件在 YYY。"
        System.out.println(ctx.i18n.msg("status.loaded", start + "; " + path));

        // 第八步：拼装"活动状态"这一行，这是整个输出里最核心的信息。
        // WindowsServiceManager.activeState(info.state()) 把服务的当前状态
        // （state）翻译成人话，比如 RUNNING（运行中）、STOPPED（已停止）、
        // PAUSED（已暂停）等，返回的是类似 "运行中 (running)" 这样的字符串。
        String active = WindowsServiceManager.activeState(info.state());
        // 下面这个 if 判断有点绕，拆开看：
        //   条件一：info.processId() > 0 —— 进程号大于 0，说明服务确实
        //           有一个活着的进程（进程号是操作系统分配的，永远是正整数，
        //           如果是 0 或者负数，就说明这个服务根本没有在跑）。
        //   条件二：info.startedIso() != null —— 启动时间不是 null。
        //   条件三：!info.startedIso().isEmpty() —— 启动时间字符串不是空串。
        // 三个条件必须同时成立（用 && 连接），才会执行下面的代码。
        // 为什么要这么谨慎？因为外部数据不可信：有些服务虽然报告了进程号，
        // 但可能没有启动时间；或者有启动时间字段但内容是空的。
        // 只有确认"进程确实活着 + 启动时间确实存在且有内容"，我们才敢
        // 在状态后面追加"自某某时间起运行"这样的补充说明，
        // 否则拼出来就是残缺的句子，反而误导用户。
        if (info.processId() > 0 && info.startedIso() != null
                && !info.startedIso().isEmpty()) {
            // 这里把 "status.since" 模板的内容（大概是 "since ..." / "自...起"）
            // 追加到 active 字符串后面，中间用空格隔开。
            // formatSince(info.startedIso()) 负责把 ISO 格式的启动时间字符串
            // 转换成 "yyyy-MM-dd HH:mm:ss" 这种人类友好格式，
            // 具体转换逻辑见本类最下面的 formatSince 方法。
            active += " " + ctx.i18n.msg("status.since", formatSince(info.startedIso()));
        }
        // 打印完整的活动状态行，比如：
        //   "- 运行中 (running) 自 2024-01-15 09:30:45 起"
        System.out.println(ctx.i18n.msg("status.active.label", active));

        // 第九步：如果服务有进程号（> 0，说明它正在运行），
        // 就单独打印一行主进程号（PID）。PID 对排障特别有用：
        // 用户拿到 PID 之后，可以直接用任务管理器或者
        // "tasklist /FI \"PID eq 1234\"" 之类的命令去进一步查看
        // 这个进程占了多少内存、CPU 使用率多高，甚至强制结束它。
        // 所以把它单独打一行，方便用户复制。
        if (info.processId() > 0) {
            System.out.println(ctx.i18n.msg("status.mainpid", info.processId()));
        }
        // 这一路查下来都顺顺利利，没有走到"没找到"那个分支，
        // 所以返回退出码 0 表示成功。
        return 0;
    }

    // ------------------------------------------------------------------------
    // formatSince 是一个"纯工具方法"：
    //   它是 static 的，意味着不需要 StatusCommand 的实例就能调用，
    //   因为它不依赖任何实例字段（比如 ctx），输入输出完全由参数决定，
    //   这类方法在 Java 里就叫"静态工具方法"，通常放最后面。
    //   它也是 private 的，意味着只有本类内部能调用，对外部完全隐藏，
    //   因为别的类根本不需要关心"怎么把时间格式化"这种内部细节。
    // 它的职责：把 Windows 服务返回的 ISO-8601 格式的启动时间字符串
    // （例如 "2024-01-15T09:30:45.123456+08:00"）解析成 OffsetDateTime 对象，
    // 再用 DISPLAY_TIME 格式化器输出成 "2024-01-15 09:30:45" 这种简洁格式。
    // 为什么要费这个劲解析再格式化？因为 Windows 返回的原始 ISO 字符串
    // 里带着时区偏移和可能的小数秒，直接原样打印给用户看太"理工味"了，
    // 用户只想知道"这服务啥时候启动的"，不需要看那么精确。
    // 注意参数名 iso 暗示了它期待的是 ISO 格式的字符串。
    // ------------------------------------------------------------------------
    private static String formatSince(String iso) {
        // try-catch：把"可能出错的操作"包在 try 里，出错时跳进 catch 处理。
        // 为什么这里会出错？因为 iso 字符串来自 Windows 服务（外部世界），
        // 我们永远不能 100% 保证它的格式是标准、合法的 ISO 时间格式。
        // 万一某个服务返回的字符串格式很怪（比如少了时区，或者干脆是乱码），
        // OffsetDateTime.parse() 就会抛出一个 DateTimeParseException 异常。
        // 如果不捕获这个异常，程序就会直接崩溃（异常一路向上抛，最终
        // 导致命令行工具报错退出），因为一点点时间格式问题就让整个命令
        // 崩溃，太不划算了，所以这里选择"优雅降级"。
        try {
            // OffsetDateTime.parse(iso) 把字符串解析成带时区的日期时间对象。
            // 然后立刻链式调用 .format(DISPLAY_TIME)，
            // 用我们定义好的格式化器把它变成 "yyyy-MM-dd HH:mm:ss" 字符串，
            // 最后作为方法的返回值返回给调用方。
            // 这种"解析完马上格式化"的一行式写法（链式调用）很常见，
            // 读的时候可以按从左到右的顺序理解：先 parse（解析），再 format（格式化）。
            return OffsetDateTime.parse(iso)
                    .format(DISPLAY_TIME);
        } catch (DateTimeParseException e) {
            // 走到这个 catch 分支，说明上面解析失败了，iso 不是合法的 ISO 时间。
            // 这时候我们选择"原样返回"：不格式化，直接把原始字符串 iso 还回去。
            // 这样做的考虑是：与其打印一个错误的、编造出来的时间，
            // 不如老老实实把原始值给用户看，至少信息是真实的；
            // 同时也保证了 formatSince 这个方法的"契约"——无论输入多离谱，
            // 它都会返回一个非 null 的字符串，调用方永远不用担心空指针。
            // 变量 e（异常对象）在这里其实没有用到，可以不写名字，
            // 但 Java 7 之后的规范写法就是 catch (类型 变量名)，
            // 所以保留这个 e，注释说明一下它只是个"占位"，不是疏忽。
            return iso;
        }
    }
}
