package com.systemwin.commands;

import com.systemwin.cli.Args;

/**
 * Compatibility no-op. Units are read live from the Service Control Manager,
 * so there is nothing to reload.
 *
 * 中文翻译（白话版）：
 * 这个类其实是一个"兼容性空操作"（compatibility no-op）。
 * 什么叫做"空操作"呢？就是说，这个命令被调用的时候，其实什么都不用真正去做，
 * 它只是一个"摆设"，一个"占位符"，存在的意义仅仅是为了让命令行接口（CLI）
 * 能够识别出"daemon reload"（重新加载守护进程）这个命令，而不至于报"找不到命令"的错误。
 *
 * 为什么要这样做呢？原因在下面这句话里已经说得很清楚了：
 * 所有的服务单元（unit）都是直接从 Windows 的"服务控制管理器"（Service Control Manager，
 * 简称 SCM，你可以把它理解成 Windows 操作系统里专门负责管理各种服务的一个大管家）
 * 实时读取（read live）的。
 *
 * 也就是说，我们每次需要某个服务的信息时，都是当场、立刻、现查现用的，
 * 根本没有把数据先缓存（cache）到我们自己的内存里。
 * 既然我们没有缓存任何东西，那么"重新加载"（reload）这个概念自然就无从谈起了——
 * 你都没有缓存，你重新加载什么呢？加载空气吗？
 *
 * 打个比方：如果你家冰箱里的牛奶是每天早上去超市现买的，
 * 那就不存在"把冰箱里的旧牛奶倒掉、换上新牛奶"这个操作，
 * 因为冰箱里从来就没有放过旧牛奶。这个类就是这个道理。
 *
 * 所以这个命令的实现就是一个彻头彻尾的"空转"：打印一句提示信息，
 * 然后返回 0（表示成功），假装自己完成了"重新加载"这个工作。
 * 这样做是为了保持命令行接口的兼容性——别的系统、别的平台可能有"reload"这个命令，
 * 我们 Windows 这边也得有这个命令，哪怕它什么都不做，命令的名字也得在，
 * 否则写脚本的人调用它就会失败。
 */
public final class DaemonReloadCommand implements Command {

    // ========================================================================
    // 成员变量区（fields）
    // ========================================================================
    //
    // 下面这个 ctx 是 CommandContext 类型，名字是 context（上下文）的缩写。
    // 什么是"上下文"呢？你可以把它想象成一个"万能背包"或者"工具包"，
    // 里面装着这个命令在执行过程中可能需要用到的一切东西，
    // 比如国际化（i18n）消息文本、配置信息、日志对象等等。
    //
    // 为什么不用一个全局变量（global variable）或者静态变量（static variable）
    // 来存放这些东西呢？因为那样做会让代码难以测试、难以维护——
    // 全局变量谁都能改，改乱了很难查。而把依赖通过构造函数传进来
    // （这就是著名的"依赖注入" Dependency Injection 思想），
    // 每个命令实例自己拿着自己的那份上下文，清晰又安全。
    //
    // 注意：这个字段是 final 的，意思是它一旦在构造函数里被赋值，
    // 就永远不能再被修改了。这是 Java 里一个非常好的习惯：
    // 能 final 就 final，可以防止别人（包括未来的你自己）不小心把它改掉，
    // 也顺便告诉读代码的人："这个字段构造完就定型了，放心用。"
    private final CommandContext ctx;

    // ========================================================================
    // 构造函数（Constructor）
    // ========================================================================
    //
    // 构造函数的作用是"创建对象"：当你写下 new DaemonReloadCommand(ctx) 的时候，
    // Java 就会调用这个构造函数，把传进来的 ctx 保存到上面那个 final 字段里。
    //
    // 有人可能会问：为什么参数名和字段名都叫 ctx？这不冲突吗？
    // 不冲突，因为 Java 里有个规则叫"就近原则"：在构造函数内部，
    // 直接写 ctx 指的是参数；想指字段，必须写 this.ctx。
    // 所以这里 this.ctx = ctx 的意思就是：
    // "把参数 ctx 的值，塞进我自己的成员字段 ctx 里面。"
    // this 关键字指的就是"当前这个对象自己"。
    //
    // 这种"参数名和字段名故意取一样，然后用 this 区分"的写法非常常见，
    // 几乎是 Java 社区的一种惯例（convention），读起来也很直观：
    // 一眼就能看出"我是在给自己赋值"。
    public DaemonReloadCommand(CommandContext ctx) {
        this.ctx = ctx;
    }

    // ========================================================================
    // 命令主入口方法（run）
    // ========================================================================
    //
    // @Override 注解的意思是：告诉 Java 编译器，
    // "我这个 run 方法是重写（override）自接口 Command 里的那个 run 方法"。
    // 如果接口里根本没有这个方法，或者方法签名（参数、返回值）对不上，
    // 编译器就会直接报错，帮我们提前发现低级错误，非常贴心。
    //
    // 方法签名解读：
    //   public     —— 任何人都可以调用我；
    //   int        —— 我返回一个整数，这个整数就是"进程退出码"（exit code），
    //                  0 表示一切正常（成功），非 0 表示出错了；
    //   run        —— 方法名，运行的意思；
    //   Args args  —— 参数，里面装着用户在命令行敲的那些额外参数
    //                 （比如 daemon reload --force 里的 --force 之类）。
    //
    // 这个方法的完整执行流程（说人话）：
    //   第 1 步：调用 ctx.i18n.msg("daemon.reloaded")。
    //           ctx 是我们上面存下来的上下文对象；
    //           i18n 是 internationalization（国际化）的缩写，
    //           因为 i 和 n 之间有 18 个字母，所以简称 i18n，这是业界惯例；
    //           i18n.msg(...) 就是"根据 key 查翻译文本"的方法，
    //           它会去语言资源文件（比如 messages.properties 或 messages_zh.properties）
    //           里查找 key 为 "daemon.reloaded" 的那条文本，
    //           然后根据当前系统的语言设置，返回对应语言的那句话。
    //           比如系统是英文就返回 "Daemon reloaded."，
    //           系统是中文就返回 "守护进程已重新加载。" 之类的内容。
    //           这样做的好处是：程序代码里一个中文字都不用写，
    //           所有界面文本都集中放在资源文件里，将来想加语言、改措辞，
    //           只需要改资源文件，完全不用动 Java 代码。
    //
    //   第 2 步：把查出来的那句话用 System.out.println(...) 打印到标准输出
    //           （也就是用户看到的控制台/终端窗口里）。
    //           println 是 print line 的缩写，意思就是"打印一整行然后换行"。
    //
    //   第 3 步：return 0。返回 0 表示"这个命令执行成功了"。
    //           因为前面说过，这个命令本质上是空操作，不需要做任何真正的加载工作，
    //           所以永远都是成功的，永远返回 0。
    //           哪怕将来 Windows 服务管理器那边出了什么状况，这个命令也无从知晓，
    //           因为它压根不去查——它连查都不查，又怎么会失败呢？
    //
    // 细心的读者可能注意到：方法里用了 args 参数吗？没有！
    // 是的，这个空操作命令完全无视用户传入的任何参数。
    // 你传 --force 也好，传 --verbose 也罢，它都当没看见。
    // 这也是"兼容性占位命令"的典型特征：接口上签名齐全，行为上空空如也。
    //
    // 另外提一句设计上的关系：DaemonReloadCommand 实现了 Command 接口，
    // 也就是说，只要实现了 Command 接口的类，都保证有 run(Args) 这个方法，
    // 这样上层代码（比如命令分发器 dispatcher）就可以"面向接口编程"——
    // 它不需要知道具体是哪个命令类，只需要把参数丢给 run 方法，
    // 命令自己就知道该怎么处理，这就是多态（polymorphism）的威力。
    @Override
    public int run(Args args) {
        // 打印"守护进程已重新加载"的本地化提示信息（实际什么都没做，纯属走个过场）。
        // 注释里的中文翻译：向用户输出一条"daemon.reloaded"对应的、符合当前语言的消息。
        System.out.println(ctx.i18n.msg("daemon.reloaded"));
        // 返回成功退出码 0，表示命令"顺利"完成（虽然啥也没干）。
        return 0;
    }
}
