package com.systemwin.commands;

import com.systemwin.cli.Args;

/**
 * Shows the compiled-in help text (OUTPUT-<lang>.txt).
 *
 * 上面这行英文注释的意思是：
 * "显示编译进程序里的帮助文本（来源于 OUTPUT-<lang>.txt 文件）。"
 *
 * 这句话虽然短，但里面其实藏着好几个值得慢慢琢磨的知识点，
 * 我们一个一个掰开揉碎了讲：
 *
 * （一）什么是"帮助文本"（help text）？
 * 任何一个像样的命令行程序，都会提供一个"帮助"功能：用户不知道
 * 怎么用这个工具的时候，敲一句 help（或者 -h、--help）就能看到
 * 一份使用说明，告诉他这个程序支持哪些命令、每个命令怎么用、
 * 有哪些参数等等。SystemWin 也不例外，它把这份说明文字集中放在
 * 了专门的 OUTPUT-*.txt 文件里，而不是散落在代码的各个角落。
 * 这样做的好处显而易见：改文案的时候只需要改那个文本文件，
 * 完全不用重新编译代码，连不懂编程的人都能轻松维护。
 *
 * （二）OUTPUT-<lang>.txt 里的 <lang> 是什么意思？
 * <lang> 是一个占位符，代表"语言"（language）。SystemWin 支持
 * 多语言界面，所以帮助文本也得分语言存放：比如 OUTPUT-zh.txt
 * 放中文帮助，OUTPUT-en.txt 放英文帮助。程序启动的时候会根据
 * 用户当前选择的语言，去加载对应语言的那一份帮助文件。
 *
 * （三）为什么说"编译进"（compiled-in）？
 * 这些帮助文本并不是程序运行时才去磁盘上现找的，而是在编译阶段
 * 就被打包进 jar 包（或者说类路径）里了。这样用户拿到手的就是
 * 一个完整的、自包含的程序，不管他当前在哪个目录下运行，帮助
 * 文本都稳稳当当地躺在程序内部，永远找得到，不会出现"文件丢失
 * 导致帮助显示不出来"这种尴尬情况。
 *
 * （四）这个类是干什么的？一句话总结：
 * HelpCommand 就是"帮助命令"这个具体功能的具体实现类。用户输入
 * help 命令时，框架会创建这个类的对象，然后调用它的 run 方法，
 * 让它把帮助文本打印到屏幕上，任务就算完成了。
 */
public final class HelpCommand implements Command {

    /*
     * 【字段：ctx（CommandContext，命令上下文）】
     * 我们先看看这个字段的类型：CommandContext。它是什么东西呢？
     * 简单说，它是"一个装满了各种公用依赖的大袋子"，或者说是一个
     * "服务定位器"。SystemWin 的很多命令（start、stop、status 等）
     * 干活的时候都需要用到一些公共的东西——比如多语言翻译对象 i18n、
     * 和 Windows 服务打交道的 services 对象等等。与其让每个命令自己
     * 到处去 new、去查找这些依赖，不如把它们统一收集到一个
     * CommandContext 里，谁需要谁就从里面拿。这就是"依赖注入"
     * （Dependency Injection）思想的一种朴素体现：对象不自己去
     * 找依赖，而是由外部把依赖"喂"给它。
     *
     * 注意这个字段是 private final 的：
     * （1）private 表示这个字段只有 HelpCommand 自己能用，别的类
     *     碰都碰不到——这是封装（encapsulation）的基本要求，防止
     *     外部代码随便乱改内部状态。
     * （2）final 表示这个引用一旦在构造方法里被赋值，就永远不能
     *     再指向别的对象了。为什么这么较真？因为 HelpCommand 从
     *     构造出来到用完为止，它需要的上下文是固定不变的；如果
     *     中途允许别人把 ctx 偷偷换成另一个对象，程序的运行结果
     *     就会变得不可预测，出 bug 的概率大大增加。final 就是
     *     一道"保险锁"，从语言层面杜绝这种乱换引用的操作。
     *
     * 顺便说一下：这个字段名叫 ctx，其实就是 Context（上下文）
     * 的缩写。写代码的人都有点懒，喜欢用缩写，所以看到 ctx、
     * i18n 这种名字不要慌，记住它们各自的全称和含义就行。
     */
    private final CommandContext ctx;

    /*
     * 【构造方法：HelpCommand(CommandContext ctx)】
     * 这是 HelpCommand 的构造方法（constructor），也就是"创建对象
     * 时自动调用的初始化函数"。它做的事情非常简单：把外面传进来的
     * ctx 参数原封不动地存进自己的 ctx 字段里。
     *
     * 有人可能会问：这不是脱裤子放屁吗？参数叫什么，字段也叫什么，
     * 直接 this.ctx = ctx 不就完了？对，表面上看确实绕了一下，但
     * 这一步"赋值"恰恰是依赖注入的关键所在：HelpCommand 自己不
     * 知道（也不关心）CommandContext 是怎么创建出来的，它只负责
     * "接住"别人递过来的上下文。谁递的呢？通常是由命令调度框架
     * （也就是负责解析用户输入、把命令分发到对应实现类的那部分
     * 代码）在创建 HelpCommand 的时候递进来的。
     *
     * 为什么不在 run 方法里再创建 CommandContext？因为那样做每个
     * 命令都得重复造轮子，而且造出来的还是各自独立的副本，根本
     * 没法共享同一个 i18n 翻译对象。把依赖在构造阶段就传进来，
     * 既省事又保证了全局只有一份共享状态。
     */
    public HelpCommand(CommandContext ctx) {
        this.ctx = ctx;
    }

    /*
     * 【方法：run(Args args)】
     * 这个方法上面标着 @Override，意思是"重写父接口 Command 里定义
     * 的方法"。Command 接口规定：凡是命令类都必须实现一个 run 方法，
     * 接收参数、返回退出码。HelpCommand 作为"帮助命令"，当然也要
     * 遵守这条规定，把自己真正要干的事情写在这个 run 方法里。
     *
     * 这个方法就是整个帮助命令的"核心工作间"，总共只有两行代码，
     * 我们一行一行来看：
     *
     * （一）第一行：System.out.print(ctx.i18n.help());
     * 这行代码做了三件事，套娃一样一层层往里剥：
     *   1. ctx.i18n：从刚才那个上下文大袋子里，把多语言翻译对象
     *     i18n 拿出来。i18n 是 Internationalization（国际化）的
     *     缩写（i + 中间18个字母 + n），专门负责"根据当前语言返回
     *     对应语言的文本"。
     *   2. .help()：调用 i18n 对象上的 help() 方法。这个方法会去
     *     读取刚才讲的 OUTPUT-<lang>.txt 帮助文件，把里面的内容
     *     作为一整段字符串返回出来。注意！help() 方法返回的是
     *     文本内容，它本身并不会把文字打印出来，它只负责"取货"，
     *     不负责"送货"。
     *   3. System.out.print(...)：把 help() 取回来的那一大段帮助
     *     文本，通过 System.out（标准输出流，也就是控制台）打印到
     *     屏幕上，让用户亲眼看到。print 后面没有 ln，意思是打印
     *     完不自动换行——因为帮助文件的内容里通常已经自带换行了，
     *     这里就无需再多加一个空行，免得排版变得难看。
     *
     * 可能有人好奇：为什么不直接用英文写死一段帮助文字，而要绕
     * 这么一大圈去读文件、走 i18n？因为 SystemWin 要支持多语言！
     * 如果帮助文本是写死在代码里的，那想支持中文、英文两种语言
     * 就得写两遍、还得用 if 判断当前语言——代码又丑又难维护。
     * 现在这样设计，语言相关的部分全部交给 i18n 去处理，命令本身
     * 一行都不用改，加一种新语言只需要新增一个文本文件，这就是
     * "关注点分离"（separation of concerns）思想的实际应用：
     * 命令只关心"把帮助打出来"，语言细节交给专门的组件去操心。
     *
     * （二）第二行：return 0;
     * 命令执行完必须返回一个"退出码"（exit code），这是给操作系统
     * 和调用方看的信号：0 表示"一切正常，成功结束"。在 Windows 的
     * 命令行里，你可以用 echo %ERRORLEVEL% 看到上一条命令的退出码。
     * 这里的 0 就是在告诉外界：帮助打印得很顺利，没有出任何岔子。
     * 如果哪天打印过程中出了异常，程序会抛异常而不是返回 0，
     * 调用方就能据此判断执行失败。
     *
     * 最后总结一下 HelpCommand 的完整工作流程，方便初学者把整条
     * 链路串起来：
     *   用户输入 help
     *     → 命令框架解析出"这是 HelpCommand"
     *     → 框架创建 HelpCommand 对象（顺带把 CommandContext 递进去）
     *     → 框架调用 run(Args args)
     *     → run 内部通过 ctx.i18n.help() 取回帮助文本
     *     → System.out.print 把文本打印到控制台
     *     → return 0 宣告"大功告成"。
     * 整个过程环环相扣，每一层各司其职，这就是一个结构良好的命令
     * 类该有的样子：简单、清晰、只做一件事。
     */
    @Override
    public int run(Args args) {
        System.out.print(ctx.i18n.help());
        return 0;
    }
}
