package com.systemwin.commands;

import com.systemwin.Version;
import com.systemwin.cli.Args;

/*
 * =====================================================================
 * 下面的这段 Javadoc 是原来就有的英文注释，我们先原封不动地保留它，
 * 然后呢，再用中文把它翻译一遍，顺便再多说几句废话，帮助大家理解。
 *
 * 原英文注释：
 * "Prints version information (also shown in the startup banner)."
 * 翻译成中文就是：
 * "打印版本信息（这个版本信息在程序启动时显示的那张横幅 banner 里也会出现）。"
 *
 * 为什么要保留这份英文注释呢？因为原作者可能是一个英语使用者，
 * 或者项目里约定俗成要用英文写注释，所以我们不能随便把英文删掉，
 * 只能在旁边额外补充中文说明，这样两种语言的读者都能看懂。
 *
 * 简单来说：这个类是专门负责"打印版本号"这个任务的小工具类。
 * 它做的事情非常单一，就是告诉用户当前这个 SystemWin 程序是什么版本。
 * 在软件工程里，我们管这种"一个类只做一件事"的设计思想叫做
 * "单一职责原则"（Single Responsibility Principle, 简称 SRP），
 * 意思是说每个类都应该只有一个让它改变的理由，
 * 这样代码才好维护、好测试、好理解。
 *
 * 另外，这个类为什么叫 "final" 呢？final 在 Java 里表示"最终"、
 * "不可改变"的意思。一个类被标记为 final，就意味着：
 *   1. 别的类不能继承（extends）它；
 *   2. 别的类不能通过继承来偷偷修改它的行为。
 * 对于一个功能如此简单的类来说，根本没必要让别人继承它，
 * 所以直接加上 final 反而是最安全、最省心的做法，
 * 这也能防止别人以后写出一些奇奇怪怪的继承代码。
 * =====================================================================
 */
/** Prints version information (also shown in the startup banner). */
/* 中文翻译：打印版本信息（启动横幅 banner 中也会显示同样的版本信息）。 */
// 注意啦：这个类实现了 Command 接口，也就是说它是一位"命令"家族的成员，
// 将来会被命令行分发器（dispatcher）根据用户敲的命令名找到并执行。
// 用户敲 "version" 的时候，系统就会创建一个 VersionCommand 对象并调用它的 run 方法。
public final class VersionCommand implements Command {

    /*
     * 这个类里面有一个私有成员变量，名字叫 ctx，类型是 CommandContext。
     * 这里我们有必要好好解释一下这个 ctx 到底是什么东西：
     *
     * CommandContext 可以理解成"命令的执行环境/上下文"，
     * 它像一个随身携带的"工具包"或者"百宝箱"，
     * 里面装着这个命令在执行过程中可能需要用到的各种依赖对象，
     * 比如说国际化（i18n）消息服务、日志对象、配置信息等等。
     *
     * 为什么要用成员变量把这个 ctx 存起来呢？
     * 因为构造函数（Constructor）在创建对象的时候会把它传进来，
     * 而我们后面在 run() 方法里还要用到它，
     * 所以必须先把它保存在成员变量里，
     * 这样 run() 方法才能通过 this.ctx 来访问它。
     * 这种"在构造函数里接收依赖，然后存起来供以后使用"的做法，
     * 在软件设计里有一个响当当的名字，叫做
     * "依赖注入"（Dependency Injection, 简称 DI）。
     *
     * 另外注意，这个成员变量是 private final 的：
     *   - private 表示只有本类内部能访问它，外面的人看不到，这叫"封装"（Encapsulation），
     *     可以保护内部数据不被外部随意篡改；
     *   - final 表示这个变量一旦在构造函数里被赋值，以后就再也不能改变了，
     *     这能保证这个命令在执行期间始终使用同一个上下文，不会中途被换掉，
     *     从而避免一些难以排查的、莫名其妙的 bug。
     */
    private final CommandContext ctx;

    /*
     * 下面这个就是构造函数（Constructor）。
     * 构造函数的名字必须和类名完全一样，这里类名叫 VersionCommand，
     * 所以构造函数也叫 VersionCommand，一个字母都不能差，
     * 否则 Java 编译器就会认为这不是构造函数，而是一个普通方法。
     *
     * 构造函数的作用是"初始化"一个对象：
     * 当外面的人写 "new VersionCommand(ctx)" 的时候，
     * 就会执行这段代码，把传进来的 ctx 赋值给上面的成员变量。
     *
     * 这里有个细节值得注意：我们只是把 ctx 这个"引用"保存下来，
     * 并没有重新创建一份新的 CommandContext，
     * 也就是说，这个命令和创建它的人共享同一个上下文对象。
     * 这样做的好处是节省内存，而且大家看到的数据是同一份，保持一致；
     * 但坏处是，如果外面的人偷偷修改了 ctx 里的内容，
     * 我们这个命令也会跟着受影响，所以使用的时候要小心一点。
     */
    public VersionCommand(CommandContext ctx) {
        // 这里把外部传入的 ctx 存到成员变量里，供后面的 run 方法使用。
        // 注意 this.ctx 里的 this 不能省，因为参数名也叫 ctx，不写 this 就会混淆。
        this.ctx = ctx;
    }

    /*
     * 下面这个 run 方法带有 @Override 注解，
     * 表示"我重写了父接口 Command 里定义的 run 方法"。
     *
     * 这里稍微展开讲一下接口（interface）的概念：
     * 接口就像是一份"合同"或者"契约"，
     * 里面只规定"你要提供哪些方法"，但不管"这些方法具体怎么实现"。
     * Command 接口规定：任何一个命令类都必须实现 run(Args args) 方法，
     * 这个方法接收一个 Args 参数（命令行参数），返回一个 int（退出码）。
     *
     * 为什么返回 int 呢？因为命令行程序的惯例是：
     *   返回 0 表示"一切正常，成功结束"；
     *   返回非 0 的数字（比如 1、2）表示"出错了"。
     * 操作系统（比如 Windows 的 cmd 或者 PowerShell）会根据这个返回值
     * 判断程序运行得怎么样，进而决定后续操作。
     * 所以这里 run 方法最后 return 0，就是告诉系统"我运行成功了，没问题！"
     *
     * @Override 注解虽然不写也能运行（因为方法签名刚好对得上），
     * 但强烈建议写上，因为它能起到"保险丝"的作用：
     * 万一哪天你把方法签名写错了（比如参数类型写错、方法名拼错），
     * 编译器会立刻报错提醒你，而不是等到运行时才发现问题，
     * 这样就能把错误扼杀在编译阶段，省去很多调试时间。
     */
    @Override
    public int run(Args args) {
        /*
         * 这行代码是整个类的"核心业务逻辑"所在，
         * 我们一行一行地拆开来讲：
         *
         *   System.out.println(...)
         *   - System.out 是 Java 提供的标准输出流，
         *     简单说就是"往控制台/终端屏幕上打印文字"的通道；
         *   - println 是 "print line" 的缩写，意思是"打印一行"，
         *     打印完之后还会自动换行，所以下次打印会从新的一行开始。
         *
         *   ctx.i18n.msg("version.line", Version.VERSION, Version.DESCRIPTION)
         *   - 通过 this.ctx 拿到前面保存的 CommandContext；
         *   - .i18n 是上下文里携带的"国际化消息服务"对象，
         *     i18n 是 internationalization 的缩写（因为 i 和 n 之间隔着 18 个字母），
         *     它的作用是：根据用户当前的语言环境（中文、英文、法文……），
         *     从对应的语言资源文件里取出翻译好的文本；
         *   - .msg("version.line", ...) 表示去取 key 为 "version.line" 的那条消息，
         *     后面的两个参数 Version.VERSION 和 Version.DESCRIPTION
         *     会被当作占位符参数填充进这条消息模板里，
         *     比如消息模板是 "Version {0}: {1}"，那么 {0} 就填版本号、{1} 就填描述文字；
         *   - 之所以要这样走 i18n，而不是直接把文字写死在代码里（比如
         *     System.out.println("Version 1.0 ...")），是因为"硬编码"文字
         *     会导致程序只能显示一种语言，将来想支持多语言就得改代码、
         *     重新编译，非常麻烦。而用 i18n 之后，加一种语言只需要
         *     新增一个资源文件就行，一行代码都不用改。
         *
         *   Version.VERSION 和 Version.DESCRIPTION 是什么？
         *   - 它们是 com.systemwin.Version 这个类里的两个静态常量（static final），
         *     分别保存了程序的版本号（比如 "1.2.3"）和一段描述性文字；
         *   - 因为是 static（静态）的，所以不需要 new 一个 Version 对象，
         *     直接拿类名点一下就能访问，非常方便；
         *   - 把版本号集中放在一个类里，而不是散落在各个文件各处，
         *     是为了"单一数据源"（Single Source of Truth）：
         *     以后升级版本号时，只需要改 Version 这一个地方，
         *     全程序用到的版本信息就都会跟着更新，绝不会出现
         *     "这边显示 1.0、那边显示 2.0" 这种尴尬的矛盾情况。
         *
         *   顺带一提：启动时显示的那张 banner（横幅）用的也是
         *   同一个 Version 类的常量，所以这个命令打印出来的版本信息
         *   和启动横幅里的版本信息永远是"同步"的、一致的，
         *   用户不用担心两边对不上号。
         */
        System.out.println(ctx.i18n.msg("version.line",
                Version.VERSION, Version.DESCRIPTION));
        /*
         * 最后返回 0，也就是"成功"的退出码，
         * 表示这个版本命令已经圆满完成了它的任务。
         * 因为打印版本信息这种操作不太可能会失败，
         * 所以这里没有任何 try-catch 之类的异常处理，
         * 代码看起来非常清爽简洁。
         */
        return 0; // 0 = 成功（success）；非 0 才表示出错（error）
    }
}
